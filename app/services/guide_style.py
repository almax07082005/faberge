# Границу предложения ищем по знаку конца фразы + пробел + заглавная/кавычка.
# Негативный lookbehind на инициал обязателен: в каталоге музея мастер записан
# как «Фирма К. Фаберже, мастер М. Перхин» (баг-репорт 31.08.2026, п. I-2), и
# наивный split порвал бы эту строку на четыре «предложения», после чего обрубок
# мог бы случайно совпасть с шаблоном «воды».
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?…])(?<!\b[А-ЯЁA-Z]\.)\s+(?=[«\"„(А-ЯЁA-Z])")
_DIGIT_RE = re.compile(r"\d")
# Границы абзацев — с ЗАХВАТОМ разделителя (группа), чтобы вернуть его на место
# байт-в-байт: «\n\n» и «\n» в рассказе значат разное, и подменять один другим мы
# не вправе. Разделителем считается любой перевод строки вместе с прилегающими
# пробелами: модель отбивает абзацы то одной строкой, то двумя.
_PARAGRAPH_SPLIT_RE = re.compile(r"([ \t]*(?:\r?\n[ \t]*)+)")

# Обороты — дословно со скриншотов п. II-5 (рассказ про яйцо-часы «Петушок»).
# Каждый шаблон подписан цитатой: список продуктовый, и через полгода должно быть
# видно, откуда взялась каждая строка и что будет, если её убрать.
_FILLER_PATTERNS: Tuple[re.Pattern, ...] = (
    # «Перед вами — настоящее произведение искусства…»
    re.compile(
        r"перед\s+вами\b[^.!?]{0,40}?(?:настоящ\w*|подлинн\w*|истинн\w*|поистине)\s*"
        r"(?:произведени|шедевр|образец|чудо|творени)"
    ),
    # «Представьте себе, как восхитилась Мария Фёдоровна, получив такой изысканный
    # и необычный подарок!» — обращение к воображению вместо факта.
    re.compile(r"\bпредставьте\b"),
    # «Сейчас вы можете полюбоваться этим шедевром и представить себе, как он
    # выглядел в руках императрицы.»
    re.compile(
        r"(?:полюбоваться|полюбуйтесь|любоваться|насладиться|насладитесь|восхититься|восхищаться)"
        r"\b[^.!?]{0,60}(?:шедевр|творени|произведени|красот|издели)"
    ),
    # «Это уникальное творение является свидетельством высокого уровня
    # мастерства…» и «Она служит напоминанием о том, что…» — оценка вместо факта.
    re.compile(
        r"(?:явля\w+|служ\w+|стал\w*|остает\w*|остаёт\w*)\s+"
        r"(?:свидетельств|напоминани|воплощени|олицетворени|подтверждени"
        r"|ярким\s+примером|символом\s+эпохи)"
    ),
    # «…даже самые обычные предметы могут стать настоящими произведениями
    # искусства, если их создать с любовью и мастерством.» — итоговая сентенция.
    re.compile(r"(?:стать|станов\w+)\s+(?:настоящ\w*\s+)?(?:произведени\w*\s+искусств|шедевр)"),
    re.compile(r"с\s+любовью\s+и\s+мастерством|создан\w*\s+с\s+любовью"),
)

# Предохранители чистки: сколько текста должно ОСТАТЬСЯ, чтобы чистку применить.
# Обоснование — в docstring `strip_filler`. Доля намеренно низкая (0.2, а не
# «треть»): на рассказе со скриншота п. II-5 воды БОЛЬШЕ, чем фактов — пять
# предложений против трёх, — и порог в треть отменял бы чистку ровно в том
# случае, ради которого она заведена. От пустого рассказа страхует MIN_KEPT_CHARS,
# а доля ловит другое: развалившееся разбиение на предложения (текст без точек),
# когда «выброшено» оказывается почти всё.
MIN_KEPT_CHARS = 120
MIN_KEPT_RATIO = 0.2


def split_sentences(text: str) -> List[str]:
    """Разбить текст на предложения, не разрывая инициалы («К. Фаберже»)."""
    stripped = (text or "").strip()
    if not stripped:
        return []
    return [s for s in _SENTENCE_SPLIT_RE.split(stripped) if s.strip()]


def is_filler_sentence(sentence: str) -> bool:
    """Предложение — «вода» из перечня музея и его можно выбросить целиком?

    Предложение с ЧИСЛОМ не выбрасывается никогда, даже если совпало с шаблоном.
    Это осознанный компромисс: датировка, номер витрины, количество — факты, и
    потерять факт хуже, чем оставить при нём эпитет. Цена компромисса —
    «Перед вами — настоящее произведение искусства, созданное в 1900 году»
    останется как есть; это надо честно назвать музею, а не выяснять потом.
    """
    if _DIGIT_RE.search(sentence or ""):
        return False
    low = (sentence or "").lower().replace("ё", "е")
    return any(p.search(low) for p in _FILLER_PATTERNS)


def strip_filler(text: str) -> Tuple[str, int]:
    """Убрать из рассказа предложения-«воду». Возвращает (текст, сколько выброшено).

    Правила и почему они такие:

    1. Выбрасывается ЦЕЛОЕ предложение, а не оборот внутри него. Вырезать кусок
       фразы — значит получить рваную грамматику, которую ещё и озвучит
       синтезатор: рассказ уходит и в ``text``, и в ``tts.synthesize``.
    2. Предложение с числом не трогаем (см. ``is_filler_sentence``).
    3. Разбиение на предложения идёт ВНУТРИ абзаца, и абзацы собираются обратно
       своими же разделителями. Прежняя редакция склеивала уцелевшие предложения
       через ``' '.join`` по всему тексту, и любой состоявшийся выброс превращал
       рассказ из четырёх абзацев в простыню без единого переноса. Для музея это
       прямое нарушение требования «карточка должна быть прогнозируемой» (п. I-2):
       форматирование зависело бы от того, нашлась в тексте вода или нет, —
       соседние экспонаты приезжали бы на фронт по-разному свёрстанными.
    4. Абзац, из которого вода вынесла всё, исчезает вместе со своим
       разделителем: пустая строка на месте выброшенного абзаца — такая же
       рваность, только на уровне вёрстки.
    5. Если после чистки осталось меньше ``MIN_KEPT_CHARS`` знаков или меньше
       ``MIN_KEPT_RATIO`` исходного объёма — возвращаем ИСХОДНЫЙ текст и ноль.
       Значит модель написала почти одну воду (или развалилось разбиение на
       предложения), и водянистый рассказ всё-таки лучше пустого: посетитель у
       витрины должен что-то услышать.
    6. Когда выбрасывать нечего, возвращается ровно тот же объект, что пришёл, —
       без пересборки и без нормализации пробелов.
    """
    original = text or ""
    if not original.strip():
        return original, 0
    # split с захватывающей группой чередует куски и разделители:
    # [абзац, разделитель, абзац, …, абзац]. Нечётные индексы — разделители.
    parts = _PARAGRAPH_SPLIT_RE.split(original)
    dropped = 0
    rebuilt: List[str] = []
    for index in range(0, len(parts), 2):
        paragraph = parts[index]
        separator = parts[index + 1] if index + 1 < len(parts) else ""
        sentences = split_sentences(paragraph)
        kept = [s for s in sentences if not is_filler_sentence(s)]
        dropped += len(sentences) - len(kept)
        cleaned_paragraph = " ".join(s.strip() for s in kept).strip()
        if not cleaned_paragraph:
            # Абзац ушёл целиком — уносим и разделитель, иначе на его месте
            # останется пустая строка (правило 4).
            continue
        rebuilt.append(cleaned_paragraph)
        rebuilt.append(separator)
    if not dropped:
        return original, 0
    cleaned = "".join(rebuilt).strip()
    if len(cleaned) < MIN_KEPT_CHARS or len(cleaned) < len(original.strip()) * MIN_KEPT_RATIO:
        return original, 0
    return cleaned, dropped
