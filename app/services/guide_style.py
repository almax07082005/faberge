# Часть 2. Перефразировки одного вопроса (п. II-2)
# ═════════════════════════════════════════════════════════════════════════════


_NUMBER_RE = re.compile(r"\d+")

# ── Действия, которые синоним-карта кластеризатора склеивает в одну лемму ────
# `question_cluster._SYNONYMS` сводит «подарил», «заказал», «принадлежал» и «чей»
# к общей лемме «владелец». Для аналитики это правильно: там считают частоту
# ТЕМЫ («вопросы про принадлежность»), и мелкие различия только дробили бы
# кластеры. В подсказках цена ровно обратная — проверено вызовом
# `dedupe_questions(['Кто заказал это яйцо?'], exclude=['Кто подарил это яйцо?'])`,
# результат пустой: один отказ на «Кто подарил это яйцо?» прячет «Кто заказал это
# яйцо?» у ВСЕХ посетителей экспоната на `GUIDE_REFUSAL_MEMORY_DAYS` дней, потому
# что `exclude` кормится ГЛОБАЛЬНОЙ памятью отказов (решение Д8). А это разные
# вопросы: заказчик и даритель — разные люди и разные ответы.
#
# Чинить приходится здесь, а не в `question_cluster`: тот модуль обслуживает
# отчёты аналитики, у него своя калибровка, и правка его синоним-карты меняла бы
# частотные кластеры в отчётах музея — то есть ломала бы соседнюю задачу ради
# этой.
#
# Признак действия работает СТОП-СИГНАЛОМ, как расхождение чисел выше, а не
# леммой: доложить его в ключ мало — при трёх общих леммах из четырёх перекрытие
# остаётся 0.75 при пороге 0.7, и вопросы всё равно склеиваются. Поэтому
# `_same_topic` сначала сверяет действия, а потом выбрасывает их из ключей и
# считает похожесть ровно так же, как считала раньше.
#
# ОГРАНИЧЕНИЕ: стоп-сигнал срабатывает, только когда действие названо в ОБОИХ
# вопросах и оба действия перечислены здесь. Односторонний случай — «Кому
# подарили это яйцо?» против «Кому принадлежало это яйцо?» — этой проверкой не
# закрывается: во втором вопросе действия нет, множества действий сравнить не с
# чем, и решение остаётся за мерой похожести.
#
# Прежняя редакция этого комментария утверждала, что такая пара «по-прежнему
# считается одной темой». Это неверно, и проверено вызовами `_same_topic`:
#   • «Кто подарил это яйцо?» / «Кому принадлежало это яйцо?» → False, но
#     разводит их НЕ признак действия, а `MIN_KEY_LEN_FOR_FUZZY`: ключи
#     {владелец, действие:подарок, кто, яйц} и {владелец, яйц}, у меньшего длина
#     2, а такие ключи склеиваются только при полном совпадении. Убрать отсюда
#     признак действия — пара всё равно разойдётся;
#   • а вот когда обоим ключам хватает длины, ограничение видно по-настоящему:
#     «Кому подарили это яйцо после революции?» / «Кому принадлежало это яйцо
#     после революции?» → True, второй вопрос из подсказок исчезает. Ключи
#     {владелец, действие:подарок, революц, яйц} и {владелец, революц, яйц}:
#     второй вложен в первый после выброса действий, и это трактуется как
#     сужение темы, а не как разные действия.
# Так что ограничение реально, но его цена — не та пара, которой оно
# иллюстрировалось. Расширять список действий наугад дороже, чем оставить это
# видимым: лишнее действие в списке расклеивает настоящие перефразировки, а
# расклеенная пара — это та самая жалоба п. II-2.
_ACTION_PREFIX = "действие:"
_ACTION_ASPECTS: Tuple[Tuple[str, re.Pattern], ...] = (
    # «Кто заказал?», «по чьему заказу», «заказанное герцогиней» — один аспект.
    ("заказ", re.compile(r"заказ")),
    # «Кто подарил?», «кому подарили», «преподнёс в дар».
    ("подарок", re.compile(r"подар|преподнес")),
)


def _action_aspects(question: str) -> set:
    """Какие взаимоисключающие действия названы в вопросе (заказ ≠ подарок)."""
    low = normalize(question)
    return {
        _ACTION_PREFIX + name for name, pattern in _ACTION_ASPECTS if pattern.search(low)
    }


# Начиная со скольких лемм ключ можно сравнивать «на глазок» (по перекрытию).
# Ключи короче склеиваются ТОЛЬКО при полном совпадении.
#
# Почему это здесь строже, чем в `question_cluster.MIN_KEY_LEN_FOR_FUZZY` (=2):
# на однолемменной разнице подсказки расходятся по смыслу чаще, чем совпадают.
# Проверено вызовом: «Кому подарили это яйцо?» ({владелец, яйц}) и «Кому
# принадлежало это яйцо после революции?» ({владелец, революц, яйц}) давали
# overlap = 1.0 и схлопывались в один вопрос — посетитель терял вторую тему.
# `question_cluster` считает частотность для отчётов аналитики, там пересклейка
# дешевле, и его порог мы не трогаем.
#
# ВНИМАНИЕ: одной этой планки НЕ хватает, и раньше здесь было написано обратное.
# Она закрывает только `min(len) <= 2`; при ключах длиной 3+ сравнение уходит в
# `_similar`, а он нормирует перекрытие на МЕНЬШИЙ ключ — то есть вложенный ключ
# даёт 1.0 при любой длине и любом пороге. Вложенность отсекается отдельно, в
# `_same_topic`; см. её докстринг.
MIN_KEY_LEN_FOR_FUZZY = 3

# Леммы, которые НЕ сужают тему, а приходят от формы вопроса. Вложение считается
# без них — иначе перефразировка выглядит как сужение и пара расклеивается.
# Откуда каждая берётся:
#   • «место» — из синоним-карты `question_cluster._SYNONYMS`: «находится»,
#     «расположен», «найти» и «где» сводятся к одной лемме. «Что внутри яйца?»
#     и «Что НАХОДИТСЯ внутри яйца?» — один вопрос, но у второго ключ на лемму
#     длиннее, и вложение отсекало склейку.
#   • «кто» и «что» — вопросительные слова: в `_STOPWORDS` кластеризатора их нет
#     (там только «какой/какая», которые не различают аспект). «Кто владел яйцом
#     до революции?» и «Кому принадлежало яйцо до революции?» отличаются ровно
#     этим: «кому» — стоп-слово, «кто» — нет.
#   • «был» — связка («кто БЫЛ владельцем» / «кому принадлежало»), тот же случай.
# Обе пары посетитель увидел бы рядом — это ровно жалоба п. II-2, ради которой
# дедупликация и заведена.
WEAK_LEMMAS = frozenset({"кто", "что", "место", "был"})


def _question_key(question: str) -> frozenset:
    """Ключ вопроса для сравнения смыслов: леммы кластеризатора, числа и действия.

    Числа добавляем сами: ``question_cluster.keywords`` отбрасывает токены короче
    двух символов и стеммер до чисел не добирается, а в подсказке число почти
    всегда и есть весь смысл различия — «Что в витрине 5?» и «Что в витрине 12?»
    это разные вопросы, и склеивать их нельзя. В аналитике такой поправки нет
    намеренно (там числа как раз шумят в частотных кластерах), поэтому правим не
    `question_cluster`, а ключ здесь. По той же причине сюда попадает признак
    действия (`_action_aspects`): «заказал» и «подарил» кластеризатор сводит к
    одной лемме, и без этого признака отказ на один вопрос прятал бы другой.
    """
    key = set(keywords(question))
    key.update(_NUMBER_RE.findall(question or ""))
    key.update(_action_aspects(question))
    return frozenset(key)


def _same_topic(a: frozenset, b: frozenset) -> bool:
    """Один ли это по сути вопрос: мера кластеризатора плюс четыре ужесточения.

    Одной меры перекрытия мало, и каждый раз она ошибается в одну сторону — в
    ПЕРЕсклейку, а склеенные разные вопросы — это потерянная для посетителя тема:

    1. Числа. «Что стоит в витрине 5?» и «Что стоит в витрине 12?» отличаются
       ровно одной леммой из четырёх — перекрытие 0.75 при пороге 0.7, и
       кластеризатор их склеил бы. Для отчётов аналитики это правильно (там
       считают частоту темы), в подсказках — нет. Расхождение чисел отменяет
       похожесть целиком.
    2. Короткие ключи. Перекрытие нормируется на меньший ключ, поэтому ключ из
       двух лемм, целиком вложенный в трёхлемменный, даёт 1.0 при любом пороге
       (см. ``MIN_KEY_LEN_FOR_FUZZY``). На подсказках такие ключи — норма, а не
       исключение.
    3. Строгое вложение при ЛЮБОЙ длине ключа. Это то же самое место, что и
       пункт 2, только планка длины его не закрывает: при ключах из трёх и более
       лемм сравнение уходит в ``_similar``, а вложенный ключ даёт там ровно 1.0.
       Проверено вызовами ``dedupe_questions`` — второй вопрос в каждой паре
       исчезал молча::

           «Из чего сделано яйцо?»    ⊂ «Из чего сделана подставка яйца?»
           «Где хранилось яйцо?»       ⊂ «Где хранилось яйцо до революции?»
           «Что означает монограмма?»  ⊂ «Что означает корона на монограмме?»

       Смысловая разница между вложением и перефразировкой прямая: лишняя лемма
       СУЖАЕТ тему (подставка, революция, корона — это новый предмет разговора),
       а перефразировка ЗАМЕНЯЕТ леммы на синонимичные, и тогда у ключей есть
       собственные, друг в друга не входящие части. Пары со скриншотов пп. II-2 и
       II-3 — именно такие, поэтому они продолжают схлопываться.

       Но лишняя лемма приходит не только от сужения темы: её добавляют
       синоним-карта кластеризатора и вопросительное слово. Проверено вызовами
       ``dedupe_questions`` — обе пары ниже расклеились и посетитель увидел бы их
       рядом, то есть ровно жалобу п. II-2::

           «Что внутри яйца?» / «Что находится внутри яйца?»
           «Кто владел яйцом до революции?» / «Кому принадлежало яйцо до революции?»

       Поэтому вложение считается по ТЕМАТИЧЕСКИМ леммам — без ``WEAK_LEMMAS``
       (см. её комментарий), — а сама похожесть ``_similar`` по-прежнему по
       полным ключам: слабая лемма тему не сужает, но и выбрасывать её из меры
       незачем.

    4. Разные действия при общей лемме. Синоним-карта кластеризатора сводит
       «заказал» и «подарил» к одной лемме «владелец», и «Кто заказал это яйцо?»
       с «Кто подарил это яйцо?» получают ОДИНАКОВЫЙ ключ. Для частотных отчётов
       это правильно, для подсказок — нет: заказчик и даритель разные, а через
       `exclude` с глобальной памятью отказов один отказ прячет второй вопрос у
       всех посетителей экспоната. Расхождение действий, как и расхождение чисел,
       отменяет похожесть целиком (см. `_ACTION_ASPECTS` и записанное там
       ограничение).

    Чего эта мера не умеет и чинить порогом не надо
        Мешок лемм не различает, К ЧЕМУ относится общая часть. «Что случилось с
        яйцом в 1917 году?» и «Что случилось с фирмой Фаберже в 1917 году?» — ни
        один ключ не вложен в другой, перекрытие 0.8, и они схлопнутся, хотя это
        разные вопросы. Разделить их можно только синтаксическим разбором, а не
        подкруткой порога: любой порог, который разведёт эту пару, расклеит и
        перефразировки со скриншотов, ради которых дедупликация заведена.
    """
    numbers_a = {token for token in a if token.isdigit()}
    numbers_b = {token for token in b if token.isdigit()}
    if numbers_a != numbers_b:
        return False
    actions_a = {token for token in a if token.startswith(_ACTION_PREFIX)}
    actions_b = {token for token in b if token.startswith(_ACTION_PREFIX)}
    if actions_a and actions_b and actions_a != actions_b:
        return False
    # Дальше действия из ключей убираем: они уже сказали всё, что могли, а как
    # обычные леммы они сдвинули бы и меру похожести, и проверку вложения — то
    # есть поменяли бы поведение на парах, к которым отношения не имеют.
    a, b = a - actions_a, b - actions_b
    if min(len(a), len(b)) < MIN_KEY_LEN_FOR_FUZZY:
        return a == b
    topical_a, topical_b = a - WEAK_LEMMAS, b - WEAK_LEMMAS
    if topical_a < topical_b or topical_b < topical_a:
        return False
    return _similar(a, b)


def dedupe_questions(questions: Iterable[str], *, exclude: Iterable[str] = ()) -> List[str]:
    """Оставить по одной формулировке на смысл, сохранив порядок.

    Скриншот музея (п. II-2): посетитель спросил «Какие именно скифские мотивы
    использованы в браслете?», получил ответ — и следующей подсказкой ему
    предлагают «Какие именно скифские мотивы Эрик Коллин использовал в дизайне
    браслета?». Точным сравнением строк такое не ловится вообще: совпадающих
    символов мало, совпадает смысл.

    ``exclude`` — формулировки, которые предлагать уже нельзя: заданные в этой
    сессии вопросы (п. II-2) и вопросы, на которые гид по этому экспонату уже
    отказался отвечать (п. II-3). Сравнение то же самое, что и внутри списка, —
    иначе «уже спросили» и «уже предлагали» разъехались бы по строгости.

    Мера похожести — ``question_cluster._similar`` (перекрытие ключевых лемм
    относительно более КОРОТКОГО ключа, порог 0.7), но не она одна: сама по себе
    эта мера склонна к ПЕРЕсклейке — вложенный ключ даёт перекрытие 1.0 при любом
    пороге, а подсказки короткие. Поэтому поверх неё стоит ``_same_topic`` с
    ЧЕТЫРЬМЯ ужесточениями (числа, минимальная длина ключа, строгое вложение и
    разные действия при общей лемме — «Кто заказал это яйцо?» ≠ «Кто подарил это
    яйцо?»). Их разбор — в докстринге ``_same_topic``; здесь только перечень, и
    он обязан совпадать с ним по числу.
    Направление компромисса выбрано осознанно: два похожих вопроса в подсказках —
    мелкая неопрятность, а склеенные разные — тема, которую посетитель уже не
    увидит. Особенно это важно для ``exclude``: туда приходит ГЛОБАЛЬНАЯ память
    отказов (решение Д8), и пересклейка прячет более узкий вопрос у ВСЕХ
    посетителей экспоната на ``GUIDE_REFUSAL_MEMORY_DAYS`` дней.
    """
    seen_keys: List[frozenset] = []
    seen_exact: set = set()
    for item in exclude:
        text = (item or "").strip()
        if not text:
            continue
        seen_exact.add(normalize(text))
        seen_keys.append(_question_key(text))

    result: List[str] = []
    for item in questions:
        text = (item or "").strip()
        if not text:
            continue
        norm = normalize(text)
        if norm in seen_exact:
            continue
        key = _question_key(text)
        if any(_same_topic(key, seen) for seen in seen_keys):
            continue
        seen_exact.add(norm)
        seen_keys.append(key)
        result.append(text)
    return result


