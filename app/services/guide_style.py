"""Стиль текстов ИИ-гида: что музей просил из них убрать (баг-репорт 31.08.2026).

Дословные претензии, ради которых модуль заведён:

  • п. II-4 — «Часто в диалоге про пасхальные шедевры предлагаются вопросы
    примерно такой формулировки: "почему мастер использовал именно
    эмаль-гильоше / алмазы / золото и т.д.?". В таких вопросах нет смысла,
    потому что все ювелирные предметы изготовлены из ювелирных материалов…
    логично, что ювелиры работали с ювелирными материалами, а не любыми
    другими.»
  • п. II-8 — скриншот блока подсказок с подписью «подобные вопросы не нужны»:
    «Сколько времени заняло создание этого предмета?», «Какие уникальные
    особенности есть у этой работы Михаила Перхина?», «Почему для украшения
    была выбрана именно жёлтая гильоше-эмаль?».
  • п. II-5 — «В текстах описания предметов очень много эпитетов и воды, суть
    часто теряется.»
  • п. II-2 — «АI-экскурсовод часто предлагает неограниченное количество
    вопросов, которые постоянно перефразирует. Вопросы об одном и том же, но
    сформулированы по-разному.»

Почему модуль, а не только правка промптов
    Промпт — это просьба к модели, и тестом без сети проверяется только его
    ТЕКСТ, а не поведение. Промпт рассказа, например, уже год требует «без
    вступлений» и держит лимит знаков — и всё равно со скриншотов музея
    приходит «Перед вами — настоящее произведение искусства…»: формально это не
    вступление. Промпты в ``llm.py`` поправлены (они снижают частоту, и мы не
    платим за то, что потом выбросим), но ГАРАНТИЮ даёт только детерминированная
    чистка, которую можно прогнать в тестах на дословных фразах со скриншотов.

Почему всё в одном модуле (решение Д1 по релизу 31.08.2026)
    Над одним и тем же пулом подсказок работают три разных запрета: запрещённые
    музеем темы (II-4/II-8), перефразировки одного вопроса (II-2) и вопросы, на
    которые гид уже отказался отвечать (II-3). Два-три независимых пост-фильтра
    в разных модулях неизбежно разъедутся: один переставит порядок, другой
    срежет до среза, третий добавит своё исключение — и наружу поедет то, чего
    никто не проверял. Поэтому вход один — ``clean_questions``.

Модуль чистый: ни БД, ни сети, ни ``settings`` — на входе текст, на выходе
текст. Флаги отката (``GUIDE_QUESTIONS_FILTER``, ``GUIDE_QUESTIONS_DEDUPE``,
``GUIDE_STORY_FILLER_FILTER``) читает вызывающий код: так модуль целиком
проверяется тестами без БД и сети, как ``guide_intel`` и ``question_cluster``.
"""
from __future__ import annotations

import re
from typing import Iterable, List, Optional, Tuple

# Нормализацию и меру похожести берём у кластеризатора вопросов намеренно: там
# уже есть словарь синонимов музейного домена, лёгкий стеммер и порог склейки,
# откалиброванный на живых вопросах посетителей (§3 ТЗ 03.08.2026). Второй
# «почти такой же» нормализатор рядом — верный способ развести их через полгода;
# ровно по этой причине так же поступает guide_mentions.
from .question_cluster import _similar, keywords, normalize

# ═════════════════════════════════════════════════════════════════════════════
# Часть 1. Бессмысленные вопросы-подсказки (пп. II-4, II-8)
# ═════════════════════════════════════════════════════════════════════════════
# Общий принцип списка: он УЗКИЙ. Ложное срабатывание здесь дороже пропуска —
# запрещённый вопрос посетитель просто не увидит в подсказках (и всегда может
# задать его сам), а хороший вопрос исчезает молча, и никто об этом не узнает.
# Поэтому каждый шаблон требует СОВПАДЕНИЯ НЕСКОЛЬКИХ признаков сразу, а не
# одного слова.

# Ювелирные материалы и техники, «выбор» которых музей считает бессмысленным
# вопросом. Слева ограничитель, чтобы «агат» не находился внутри другого слова.
_MATERIALS = (
    r"(?<![а-яa-z])(?:эмал|гильош|финифт|золот|позолот|серебр|платин|алмаз|бриллиант|"
    r"жемчуг|нефрит|рубин|сапфир|изумруд|аметист|перламутр|хрустал|слонов\w*\s+кост|"
    r"малахит|лазурит|яшм|агат|родонит|бронз|дерев|стекл|фарфор|самоцвет|драгоценн)"
)
# Глаголы «выбора»: именно они отличают претензию музея («почему ВЫБРАЛИ эмаль»)
# от нормального фактического вопроса про материал («из чего сделано»).
_CHOICE = (
    r"(?:выбра|выбор|выбир|использова|применя|применил|применен|предпоч|"
    r"остановил\w*\s+выбор)"
)
# Вопросительные зачины «почему». «Как» сюда не входит: «как сделана эмаль» —
# нормальный вопрос о технологии, музей возражает не против него.
_WHY = r"\b(?:почему|зачем|для\s+чего|с\s+какой\s+целью|по\s+какой\s+причине|чем\s+обусловлен|чем\s+объясня)"

# ── Кирпичи запрета «сколько длилось изготовление» (п. II-8, первый вопрос) ──
# Претензия музея здесь ровно одна и очень узкая: «Сколько времени заняло
# СОЗДАНИЕ ЭТОГО ПРЕДМЕТА?». Всё остальное, что начинается со «сколько лет», —
# нормальные вопросы, и музей их не трогал.
#
# Первая редакция шаблона держала «сколько времени|лет|дней» и список глаголов
# (`созда|изготов|ушло|заня|потратил|работ\w*\s+над`) просто РЯДОМ, в пределах
# сорока знаков. Этого хватило, чтобы молча съесть шесть осмысленных вопросов
# (проверено вызовами `is_meaningless_question`):
#   «Сколько лет было Марии Фёдоровне, когда мастер создал это яйцо?»
#   «Сколько лет прошло с тех пор, как создали яйцо?»
#   «Сколько лет назад создали это яйцо?»
#   «Сколько лет Фаберже работал над императорскими заказами?»
#   «Сколько дней ушло на дорогу, когда яйцо везли из Петербурга?»
#   «Сколько времени заняла реставрация этого предмета?»
# Фильтр стоит НА ЧТЕНИИ и ничего не логирует: такой вопрос исчезает бесследно,
# и узнать о потере неоткуда. Поэтому глаголы привязаны к ОБЪЕКТУ («создание
# этого предмета»), а не стоят «где-то поблизости».

# Вопрос о длительности: «сколько времени/лет/месяцев…», «как долго».
_HOW_LONG = r"(?:сколько\s+(?:времени|лет|месяцев|дней|недель|часов)|как\s+долго)"
# Слова, которые сразу после «сколько лет/времени» переводят вопрос в другую
# тему: возраст («сколько лет БЫЛО Марии Фёдоровне») и давность («сколько лет
# НАЗАД», «сколько лет ПРОШЛО»). Достаточно одного такого слова вплотную —
# запрет снимается целиком, дальше по строке смотреть уже нечего.
_NOT_DURATION = r"(?:назад|прошл\w*|было|исполн\w*|минул\w*|спустя)"
_LONG = _HOW_LONG + r"\s+(?!" + _NOT_DURATION + r"\b)"
# Изготовление как ПРОЦЕСС — существительное («заняло создание», «ушло на
# изготовление»). Именно оно отличает претензию музея от «заняла реставрация».
_MAKING_NOUN = r"(?:создани|изготовлени|изготовк|производств)"
# …или глагол в прямой связке с вопросом («как долго СОЗДАВАЛИ яйцо»). Формы
# перечислены поимённо: голое «созда» ловит и «когда мастер СОЗДАЛ это яйцо».
_MAKING_VERB = r"(?:создава|создал[аиои]?\b|изготавлива|изготовля|изготовил|делал|трудил|мастерил)"
# Глаголы «потрачено времени». Сами по себе они не про изготовление («сколько
# дней УШЛО на дорогу»), поэтому годятся только в паре с _MAKING_NOUN.
_SPENT = r"(?:ушло|уходил\w*|заня\w*|потратил\w*|потребовал\w*|длил\w*)"
# «Работал над» — только над ЭТОЙ вещью: «Сколько лет Фаберже работал над
# императорскими заказами?» — нормальный биографический вопрос, а не претензия.
_THIS_ITEM = r"(?:эт|ним\b|не[йе]\b|издели|предмет|экспонат|яйц|вещ|создани)"

# Объект изготовления. Из трёх шаблонов запрета объект был привязан к двум
# (материалы — через `_CHOICE_OBJECT`, «работал над» — через `_THIS_ITEM`), а
# шаблон сроков оставался широким: ему хватало «сколько времени» + «создание»
# где угодно рядом. Проверено вызовами `is_meaningless_question` — все шесть
# давали True и вырезались молча, хотя к жалобе музея отношения не имеют:
#   «Сколько времени заняло создание всей императорской серии?»
#   «Сколько времени заняло создание музейной экспозиции?»
#   «Сколько времени уходило на изготовление одной миниатюры у Цейнграфа?»
#   «Сколько лет ушло на создание Шуваловского дворца?»
#   «Как долго изготавливали витрины для нового зала?»
#   «Сколько месяцев делали копию яйца для выставки?»
# Претензия музея узкая: «Сколько времени заняло создание ЭТОГО ПРЕДМЕТА?».
#
# Пустой объект разрешён намеренно (ветка `[?.!]|$`): «Сколько времени ушло на
# создание?» — формулировка из `llm._questions_stub`, она закреплена тестом и
# запрещена по существу; дополнения в ней нет, потому что предмет ясен из
# контекста диалога.
#
# ОГРАНИЧЕНИЕ, которое честнее назвать, чем подогнать: «Сколько месяцев делали
# копию яйца для выставки?» остаётся зарезанным. Там «яйца» — настоящий объект
# изготовления, и отличить его от «этого яйца» можно только разбором связи
# «копию ← яйца», а не шаблоном. Формулировка редкая, а расширять исключения
# ради неё — значит снова распустить шаблон.
#
# Объект здесь СТРОЖЕ, чем `_THIS_ITEM`, и по той же причине, по какой ниже
# заведён `_THIS_WORK`: в `_THIS_ITEM` местоимение привязано предлогом («работал
# НАД этим»), а тут перед ним стоит только «создание», и голое «эт» цепляет что
# угодно. Проверено вызовами `is_meaningless_question`, все четыре давали True и
# вырезались молча:
#   «Сколько времени заняло создание этого зала?»
#   «Сколько времени заняло создание этого дворца?»
#   «Сколько времени заняло создание этой выставки?»
#   «Сколько времени заняло создание этой коллекции?»
# Это тот же класс вопросов, ради которого объект к шаблону и привязывали:
# «Сколько лет ушло на создание Шуваловского дворца?» выживал, а «создание этого
# дворца» — нет, хотя музей не возражал ни против того, ни против другого.
# Поэтому указательное местоимение засчитывается только в связке с ВЕЩЬЮ
# («этого предмета», «этой ювелирной вещи») либо когда оно само и есть весь
# объект в конце вопроса («Сколько времени заняло создание этого?»).
_MADE_THING = (
    r"(?:издели|предмет|экспонат|яйц|вещ|шедевр|шкатулк|брошь|браслет|портсигар|создани)"
)
_MAKING_THIS = (
    r"(?:(?:эт\w*\s+(?:\w+\s+){0,1})?" + _MADE_THING
    + r"|эт\w*\s*(?:[?.!]|$))"
)
_MAKING_OBJECT = r"\w*\s*(?:[?.!]|$|(?:\w+\s+){0,1}" + _MAKING_THIS + r")"

# Что стоит между глаголом выбора и материалом. Материал обязан быть ПРЯМЫМ
# ДОПОЛНЕНИЕМ глагола: хвост глагола, необязательное усилительное слово
# («использовал ИМЕННО эмаль») и не больше одного определения («выбрана именно
# ЖЁЛТАЯ гильоше-эмаль»). Тот же приём, каким выше привязаны сроки через
# `_MAKING_NOUN`.
#
# Первая редакция ставила материал просто «в окне 40 знаков» после глагола
# выбора, и этого хватало, чтобы молча съесть осмысленные вопросы (проверено
# вызовами `is_meaningless_question`, все три давали True):
#   «Зачем в яйце использован механизм, который поднимает золотую птицу?»
#   «Почему сюжет коронации выбран для яйца с золотой каретой?»
#   «Почему это яйцо перестали использовать, хотя оно золотое?»
# Второй из них — прямое нарушение обещания, записанного ниже в этом же модуле:
# «Почему мастер выбрал сюжет коронации?» под запрет попадать не должен, и
# «золотая карета» рядом ничего в вопросе не меняет.
_CHOICE_OBJECT = (
    r"\w*(?:\s+(?:именно|конкретно|так(?:ой|ую|ое|ого|их|ие)))?\s+(?:\w+\s+){0,1}"
)

_BANNED_QUESTION_PATTERNS: Tuple[re.Pattern, ...] = (
    # п. II-4 дословно: «почему мастер использовал именно эмаль-гильоше /
    # алмазы / золото и т.д.?». Он же покрывает третий вопрос со скриншота
    # п. II-8 — «Почему для украшения была выбрана именно жёлтая гильоше-эмаль?».
    # Требуются ВСЕ три признака: вопрос «почему», глагол выбора и материал
    # ПРЯМЫМ ДОПОЛНЕНИЕМ при нём — иначе под нож пошли бы «Почему мастер выбрал
    # сюжет коронации?» и «Почему яйцо назвали „Ландыши“?».
    re.compile(_WHY + r".{0,80}" + _CHOICE + _CHOICE_OBJECT + _MATERIALS),
    # п. II-8, первый вопрос со скриншота: «Сколько времени заняло создание этого
    # предмета?» — и его форма из стаба «Сколько времени ушло на создание?».
    # Изготовление обязано быть НАЗВАНО существительным: «заняла реставрация»,
    # «ушло на дорогу» под запрет не попадают. И оно обязано относиться к ЭТОЙ
    # вещи (`_MAKING_OBJECT`): «создание всей императорской серии» и «создание
    # музейной экспозиции» — вопросы, которых музей не касался.
    re.compile(_LONG + r".{0,30}?" + _SPENT + r"\s+(?:на\s+)?" + _MAKING_NOUN + _MAKING_OBJECT),
    # Тот же вопрос глаголом и без связки: «Как долго создавали яйцо?»,
    # «Сколько месяцев изготавливали это яйцо?». Глагол должен стоять ВПЛОТНУЮ
    # (не дальше двух слов): в «Сколько лет прошло с тех пор, как СОЗДАЛИ яйцо?»
    # он относится к другому вопросу — к давности, а не к длительности работы.
    # Объект тот же самый: «Как долго изготавливали ВИТРИНЫ для нового зала?»
    # запрещать не за что.
    re.compile(_LONG + r"(?:\S+\s+){0,2}" + _MAKING_VERB + _MAKING_OBJECT),
    # «Сколько лет мастер работал над этим яйцом?» — «работал над» считается
    # только когда «над» указывает на ЭТУ вещь. Иначе сюда попадал бы нормальный
    # биографический вопрос «Сколько лет Фаберже работал над императорскими
    # заказами?» (и «Сколько лет мастер работал у Фаберже?» — там «над» вообще нет).
    re.compile(_LONG + r".{0,30}?работ\w*\s+над\s+" + _THIS_ITEM),
)

# Второй вопрос со скриншота п. II-8 — «Какие уникальные особенности есть у ЭТОЙ
# РАБОТЫ Михаила Перхина?». Вынесен ОТДЕЛЬНЫМ кортежем сознательно: в п. II-4
# музей назвал только материалы и сроки, а этот вопрос попал под запрет потому,
# что в п. II-8 обведён весь блок подсказок целиком. Если окажется, что музей
# имел в виду не его, — запрет снимается удалением одной строки, без правки
# логики и без перегенерации кэша.

# «Уникальность» как оборот. Сам по себе он ничего не запрещает: музей обвёл
# вопрос про КОНКРЕТНУЮ ВЕЩЬ, а не про уникальность вообще.
_UNIQUE = (
    r"(?:уникальн\w*\s+(?:особенност|черт|детал|элемент|свойств)"
    r"|чем\s+уникал|в\s+чем\s+уникальност|уникальност\w*"
    r"|чем\s+особенн\w*)"
)
# Указание на САМ ЭКСПОНАТ: указательное местоимение и слово-предмет при нём
# («этой работы», «этого предмета», «это яйцо», «этой ювелирной вещи»).
# Строже, чем `_THIS_ITEM` выше, и намеренно: там местоимение уже привязано
# предлогом («работал НАД этим»), а здесь одинокое «эт» цепляло бы «этой эпохи»
# и «это событие».
#
# Первая редакция шаблона не требовала объекта вообще и срабатывала на чём
# угодно — проверено вызовами `is_meaningless_question`, все пять давали True:
#   «В чём уникальность коллекции Музея Фаберже?»
#   «Чем особенно это событие для истории музея?»
#   «Какие уникальные детали помогают отличить подделку Фаберже?»
#   «Какие уникальные черты у русского ювелирного искусства этой эпохи?»
#   «Чем уникален этот зал?»
# Ни один из них под претензию музея не подпадает: вопрос про музей, зал,
# эпоху или коллекцию — это не «эта работа Михаила Перхина».
_THIS_WORK = (
    r"эт\w*\s+(?:\w+\s+){0,1}"
    r"(?:работ|предмет|издели|экспонат|яйц|вещ|шедевр|шкатулк|брошь|браслет|портсигар)"
)
_ARGUABLE_QUESTION_PATTERNS: Tuple[re.Pattern, ...] = (
    # Порядок слов в вопросе свободный, поэтому обе стороны — и «уникальность …
    # этой работы», и «у этого предмета … уникальные особенности».
    re.compile(_UNIQUE + r".{0,60}" + _THIS_WORK),
    re.compile(_THIS_WORK + r".{0,60}" + _UNIQUE),
)

# Чего в списке НЕТ и не должно быть. «Из каких материалов он сделан?» (он же в
# `llm._questions_stub`) — нормальный фактический вопрос: музей возражает против
# «почему выбрали именно X», а не против перечня материалов. Так же не
# запрещаются «Почему мастер выбрал сюжет коронации?», «Почему яйцо назвали
# „Ландыши“?», «Сколько яиц создал Фаберже?» — на них есть содержательный ответ.
#
# И отдельно — вопросы о времени, которые НЕ про длительность изготовления:
# «Сколько лет было Марии Фёдоровне, когда мастер создал это яйцо?», «Сколько лет
# прошло с тех пор, как создали яйцо?», «Сколько лет назад создали это яйцо?»,
# «Сколько лет Фаберже работал над императорскими заказами?», «Сколько дней ушло
# на дорогу, когда яйцо везли из Петербурга?», «Сколько времени заняла
# реставрация этого предмета?». Все шесть отсекались первой редакцией шаблона
# сроков и закреплены тестом `test_time_questions_about_anything_else_survive`.
#
# И вопросы о длительности изготовления НЕ ЭТОГО предмета: «Сколько времени
# заняло создание всей императорской серии?», «Сколько времени заняло создание
# музейной экспозиции?», «Сколько времени уходило на изготовление одной
# миниатюры у Цейнграфа?», «Сколько лет ушло на создание Шуваловского дворца?»,
# «Как долго изготавливали витрины для нового зала?». Их отсекала вторая
# редакция — до того, как изготовление привязали к объекту (`_MAKING_OBJECT`).


def is_meaningless_question(question: str) -> bool:
    """Совпадает ли вопрос с формулировкой, которую музей просил не предлагать.

    Нормализация — как в ``guide_intel.is_refusal``: регистр и ё→е, потому что
    модель пишет и «жёлтая», и «желтая», и с заглавной буквы.
    """
    low = (question or "").lower().replace("ё", "е")
    if not low.strip():
        return False
    return any(p.search(low) for p in _BANNED_QUESTION_PATTERNS + _ARGUABLE_QUESTION_PATTERNS)


def drop_meaningless_questions(questions: Iterable[str]) -> List[str]:
    """Снять запрещённые формулировки, сохранив порядок остальных.

    Ничего не переставляет и ничем не добирает: добор «до четырёх» — это ровно
    та болезнь, на которую музей пожаловался в п. II-1 про блок «Упомянуто в
    ответе». Лучше три вопроса, чем четвёртый ради счёта.
    """
    return [q for q in questions if not is_meaningless_question(q)]


