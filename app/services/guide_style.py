# Часть 3. Единая воронка подсказок
# ═════════════════════════════════════════════════════════════════════════════


def clean_questions(
    questions: Iterable[str],
    limit: Optional[int] = None,
    *,
    drop_meaningless: bool = True,
    dedupe: bool = True,
    exclude: Iterable[str] = (),
) -> List[str]:
    """Что реально уходит посетителю: снять запреты, склеить перефразировки, срезать.

    Порядок операций не случаен. Срез ``limit`` делается ПОСЛЕДНИМ: если резать
    сначала, запрещённые и повторяющиеся формулировки съедают слоты, и на пул
    ``[запрещённый, запрещённый, A, B, C]`` при ``limit=3`` посетитель увидел бы
    один вопрос вместо трёх.

    Флаги — параметрами, а не чтением ``settings``: модуль остаётся чистым, а
    откат (``GUIDE_QUESTIONS_FILTER=false``) делает вызывающий код одной
    переменной окружения, без релиза.
    """
    # Пустые строки снимаем всегда и на любом наборе флагов: модель иногда
    # возвращает висячую строку, и она превращалась бы в пустую плашку-подсказку.
    result = [(q or "").strip() for q in questions if (q or "").strip()]
    if drop_meaningless:
        result = drop_meaningless_questions(result)
    if dedupe or exclude:
        # `exclude` действует и при выключенной дедупликации: «не предлагать то,
        # на что гид уже отказался отвечать» — это не косметика, а п. II-3.
        result = dedupe_questions(result, exclude=exclude) if dedupe else _drop_excluded(result, exclude)
    if limit is not None:
        result = result[: max(0, limit)]
    return result


def _drop_excluded(questions: Iterable[str], exclude: Iterable[str]) -> List[str]:
    """Убрать только совпадающие с ``exclude``, не трогая повторы внутри списка."""
    keys = [_question_key(q) for q in exclude if (q or "").strip()]
    if not keys:
        return [q for q in questions if (q or "").strip()]
    return [
        q
        for q in questions
        if (q or "").strip() and not any(_same_topic(_question_key(q), seen) for seen in keys)
    ]


