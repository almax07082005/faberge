"""Кластеризация вопросов посетителей по смыслу (§3 ТЗ 03.08.2026).

Зачем. Прежняя аналитика группировала вопросы по точному совпадению строки
(`lower(trim(content))`). На живых данных это вырождается: «Сколько стоит яйцо?»
и «какая цена этого яйца» — два разных вопроса с count=1 каждый, «топ частых»
превращается в список случайных формулировок, а «редкие» дублируют его.

Как. Реализован «быстрый» вариант из ТЗ — по ключевым словам, без внешних
сервисов и ML-зависимостей:

  1. нормализация: lower, ё→е, снятие пунктуации;
  2. отбрасывание пустых слов («это», «мне», «пожалуйста»). Вопросительные
     слова («сколько», «где», «когда») НЕ пустые — они задают АСПЕКТ вопроса,
     а именно аспект и надо различать: «где яйцо» ≠ «сколько стоит яйцо»;
  3. словарь синонимов: «стоит/цена/стоимость/дорого» → одна лемма `цена`,
     «мастер/автор/создатель» → `мастер` и т.д.;
  4. лёгкий стеммер (отсечение русских окончаний) для форм, которых нет в
     словаре: «яйцо/яйца/яйце» → `яйц`;
  5. ключ вопроса — множество оставшихся лемм; кластеры склеиваются жадно по
     перекрытию (см. `_similar`).

Почему не pymorphy3, как предложено в ТЗ. Лемматизатор тянет ~30 МБ словарей в
архив функции Yandex Cloud (лимит и время холодного старта), а выигрыш на
коротких вопросах музейного домена даёт тот же словарь синонимов. Отсечение
окончаний покрывает падежи существительных, ради которых лемматизация и нужна.

Модуль сознательно отделён от `crud`/роутера и общается с ними одной функцией
`cluster_questions`: «точный» вариант из ТЗ (эмбеддинги + косинусная близость)
подменяет реализацию здесь, без правок в вызывающем коде.
"""
