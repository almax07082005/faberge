_MIN_STEM = 3


@dataclass
class QuestionCluster:
    """Смысловая группа вопросов."""

    key: frozenset                                  # ключ первой (самой частой) формулировки
    count: int = 0                                  # суммарно повторений
    forms: Counter = field(default_factory=Counter)  # формулировка → сколько раз
    # Ключи всех вошедших формулировок: новая формулировка сравнивается с каждым
    # (single-link). Иначе «сколько это стоит» не склеилось бы с «сколько стоит
    # яйцо», когда кластер завёлся от «какая цена яйца» — общая лемма всего одна.
    keys: List[frozenset] = field(default_factory=list)
    # Полезная нагрузка, привязанная к вопросам кластера (id экспонатов, причины
    # отказа) — заполняется вызывающим кодом, кластеризатор её не интерпретирует.
    payload: Counter = field(default_factory=Counter)

    @property
    def question(self) -> str:
        """Представитель кластера — самая частая формулировка."""
        return self.forms.most_common(1)[0][0] if self.forms else ""

    @property
    def variants(self) -> List[str]:
        """Другие формулировки того же смысла (без представителя)."""
        return [form for form, _ in self.forms.most_common()[1:][:MAX_VARIANTS]]


# ── Нормализация ─────────────────────────────────────────────────────────────
def normalize(text: str) -> str:
    """lower + ё→е + снятие пунктуации и лишних пробелов."""
    lowered = (text or "").lower().replace("ё", "е")
    return _SPACE_RE.sub(" ", _PUNCT_RE.sub(" ", lowered)).strip()


def stem(word: str) -> str:
    """Грубое отсечение русского окончания (падежи существительных и прилагательных)."""
    for ending in _ENDINGS:
        if len(word) - len(ending) >= _MIN_STEM and word.endswith(ending):
            return word[: -len(ending)]
    return word


def keywords(text: str) -> frozenset:
    """Ключ вопроса — множество значимых лемм.

    «сколько стоит яйцо» → {сколько, цена, яйц}; «какая цена яйца» → {цена, яйц}.
    """
    result: Set[str] = set()
    for token in normalize(text).split():
        if token in _STOPWORDS or len(token) < 2:
            continue
        canonical = _SYNONYMS.get(token)
        if canonical is None:
            stemmed = stem(token)
            canonical = _STEM_SYNONYMS.get(stemmed, stemmed)
        if canonical and canonical not in _STOPWORDS:
            result.add(canonical)
    return frozenset(result)


def _similar(a: frozenset, b: frozenset) -> bool:
    """Считать ли два ключа одним смыслом.

    Мера — перекрытие относительно МЕНЬШЕГО ключа: «сколько это стоит»
    ({сколько, цена}) полностью содержится в «сколько стоит яйцо»
    ({сколько, цена, яйц}), и это один и тот же вопрос. Односложные ключи
    склеиваются только при точном совпадении (см. MIN_KEY_LEN_FOR_FUZZY).
    """
    if not a or not b:
        return a == b
    if a == b:
        return True
    if min(len(a), len(b)) < MIN_KEY_LEN_FOR_FUZZY:
        return False
    overlap = len(a & b) / min(len(a), len(b))
    return overlap >= SIMILARITY_THRESHOLD


# ── Публичный интерфейс ──────────────────────────────────────────────────────
def cluster_questions(rows: Iterable[Tuple[str, int]], payloads: Iterable[Sequence] = ()) -> List[QuestionCluster]:
    """Сгруппировать формулировки по смыслу.

    :param rows: пары «формулировка, сколько раз встретилась».
    :param payloads: необязательная параллельная последовательность наборов
        значений (id экспонатов, причины отказа), которые надо просуммировать по
        кластеру. Смысл значений кластеризатору неизвестен.
    :return: кластеры по убыванию суммарной частоты.

    Алгоритм — объединение непересекающихся множеств (union-find) по похожести
    ключей, а не «жадное подклеивание к первому подходящему кластеру»: жадный
    вариант зависел бы от порядка обработки. Например, «какая цена яйца»
    ({цена, яйц}) не похожа на «Сколько это стоит» ({сколько, цена}) напрямую,
    но обе похожи на «сколько стоит яйцо» ({сколько, цена, яйц}) — и должны
    оказаться в одной группе независимо от того, какая строка пришла первой.

    Сравниваются только ключи, у которых есть ХОТЯ БЫ ОДНА общая лемма
    (обратный индекс `by_lemma`): у ключей без пересечения похожести всё равно
    не будет, а перебор всех пар на тысячах формулировок был бы квадратичным.
    """
    payload_list = list(payloads)
    indexed = [
        (text, count, payload_list[i] if i < len(payload_list) else ())
        for i, (text, count) in enumerate(rows)
    ]
    # Сортировка по частоте (при равенстве — по тексту) делает результат
    # детерминированным независимо от порядка строк из БД.
    indexed.sort(key=lambda item: (-item[1], item[0]))

    unique_keys: List[frozenset] = []
    key_index: Dict[frozenset, int] = {}
    for text, _count, _payload in indexed:
        key = keywords(text)
        if key not in key_index:
            key_index[key] = len(unique_keys)
            unique_keys.append(key)

    parent = list(range(len(unique_keys)))

    def find(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(a: int, b: int) -> None:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)  # корнем остаётся более частый ключ

    by_lemma: Dict[str, List[int]] = {}
    for i, key in enumerate(unique_keys):
        candidates = {j for lemma in key for j in by_lemma.get(lemma, ()) if j != i}
        for j in candidates:
            if _similar(unique_keys[j], key):
                union(i, j)
        for lemma in key:
            by_lemma.setdefault(lemma, []).append(i)

    clusters: Dict[int, QuestionCluster] = {}
    for text, count, payload in indexed:
        key = keywords(text)
        root = find(key_index[key])
        cluster = clusters.get(root)
        if cluster is None:
            cluster = clusters[root] = QuestionCluster(key=unique_keys[root])
        if key not in cluster.keys:
            cluster.keys.append(key)
        cluster.count += count
        cluster.forms[text] += count
        cluster.payload.update(payload)

    result = list(clusters.values())
    result.sort(key=lambda c: (-c.count, c.question))
    return result
