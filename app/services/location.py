"""Формулировка расположения предмета — одна на весь бэкенд.

Одну и ту же фразу — «в зале 4 «Синяя гостиная», витрина 5» — посетитель видит
в двух разных местах: в ответе ИИ-гида («Найти его можно …») и в карточке
предмета, где музей просил отдавать расположение ГОТОВОЙ строкой, а не тремя
ручками, из которых её собирает фронт (баг-репорт 31.08.2026, п. I-2). Если
формулировок будет две, они разойдутся при первой же правке — и разойдутся
именно там, где это увидит музей, а не мы: посетитель не должен читать две
разные фразы про одно и то же место.

Поэтому текст живёт здесь, а `app/routers/guide.py` и сериализаторы каталога
только зовут эти функции.

Модуль чистый — ни БД, ни ORM, ни сети (как `text_normalize`): работает от
голых значений, поэтому одинаково годится и ORM-объекту гида, и данным
карточки. Функции отвечают за ФОРМАТ, а не за наличие данных — решать, привязан
ли предмет к витрине вообще, обязан вызывающий.
"""
from __future__ import annotations

from typing import Optional


# ── Зал ──────────────────────────────────────────────────────────────────────
def hall_phrase(hall_number: Optional[int], hall_name: Optional[str] = None, case: str = "nom") -> str:
    """«зал 4 «Синяя гостиная»» / «зале 4 «Синяя гостиная»» (для «в зале …»).

    У залов без номера («Вне постоянной экспозиции») `hall_number` пуст — «зал
    None» посетителю показывать нельзя (баг-репорт 28.07.2026, п.5).

    Предлог «в» сюда НЕ входит: ту же фразу печатает список залов
    (`guide._describe_halls`), и там она идёт вообще без предлога. Кто строит
    оборот «в зале …», тот предлог и добавляет — см. `location_phrase`.
    Незнакомый `case` трактуется как именительный: формулировка расположения не
    та вещь, ради которой стоит ронять ответ гида исключением.
    """
    word = "зале" if case == "prep" else "зал"
    name = f" «{hall_name}»" if hall_name else ""
    if hall_number is None:
        return f"{word}{name}" if name else word
    return f"{word} {hall_number}{name}"


# ── Витрина ──────────────────────────────────────────────────────────────────
def showcase_phrase(showcase_number: Optional[int]) -> str:
    """«витрина 5» либо «вне витрин».

    `showcase_number = NULL` — не «номер потеряли», а группа «не в витринах»
    (в путеводителе она отмечена пустым квадратом): предметы зала, стоящие вне
    витрин. Такая группа в зале одна, см. `app/models.py::Showcase`.
    """
    if showcase_number is None:
        return "вне витрин"
    return f"витрина {showcase_number}"


# ── Расположение целиком ─────────────────────────────────────────────────────
def location_phrase(
    hall_number: Optional[int] = None,
    hall_name: Optional[str] = None,
    showcase_number: Optional[int] = None,
    *,
    case: str = "nom",
    capitalize: bool = False,
    has_hall: Optional[bool] = None,
) -> str:
    """Расположение одной строкой: «в зале 4 «Синяя гостиная», витрина 5».

    Варианты вызова у двух потребителей разные, поэтому падеж и заглавная буква —
    параметры, а не два похожих текста в разных модулях:

      • ответ гида — `case="prep"`: фраза встраивается в предложение
        («Найти его можно в зале 4 «Синяя гостиная», витрина 5.»);
      • карточка предмета — `case="nom", capitalize=True`: фраза стоит отдельной
        строкой над названием, «Зал 4 «Синяя гостиная», витрина 5».

    `has_hall` отвечает на вопрос «привязана ли витрина к залу», а не «известны
    ли его номер и название»: у вызывающего с ORM-объектом ответ точный, и
    прежняя версия фразы для зала-пустышки (нет ни номера, ни названия — дефект
    данных) всё равно начинала с «в зале». По умолчанию (`None`) выводим из
    полей — этого достаточно тому, у кого на руках только значения.

    Про отсутствие витрины функция не знает намеренно: «предмет ни к чему не
    привязан» — это пустая строка у вызывающего, а не «вне витрин».
    """
    if has_hall is None:
        has_hall = hall_number is not None or bool(hall_name)

    parts = []
    if has_hall:
        hall = hall_phrase(hall_number, hall_name, case)
        parts.append(f"в {hall}" if case == "prep" else hall)
    parts.append(showcase_phrase(showcase_number))

    text = ", ".join(parts)
    return text[:1].upper() + text[1:] if capitalize else text
