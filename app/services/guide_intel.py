"""Разбор намерения реплики посетителя для ИИ-гида (B7/B9/B10).

Чистые функции без обращения к БД — легко тестируются автономно. Роутер
`/guide/chat` использует их, чтобы решить: это навигационный вопрос («как найти» —
нужна `location`), запрос списка залов («какие залы» — `referenced_halls`) или
поиск по номеру экспоната («12», «№ 12»).
"""
from __future__ import annotations

import re
from typing import List, Optional, Tuple

# Навигация: «как найти», «в каком зале», «где находится», «как пройти»…
# Осознанно не берём голое «где» — слишком широко (напр. «где сделано»).
_NAV_PATTERNS = (
    "как найти", "где найти", "где нахо", "в каком зале", "в какой витрине",
    "как пройти", "как добраться", "где посмотреть", "где увидеть", "где распол",
    "где выставл", "где стоит", "где лежит", "покажи на карте", "как дойти",
    "в каком зал",
)

# Маркеры прошедшего времени: вопрос про историю/провенанс («где выставлялось
# РАНЬШЕ»), а не про текущее местоположение. При них навигацию не включаем —
# иначе к историческому вопросу пришпилится текущий зал/витрина (B7).
_PAST_MARKERS = ("раньше", "ранее", "прежде", "когда-то", "в прошлом")

# Список залов: «какие залы», «список залов», «сколько залов», «перечисли залы»…
# НЕ включаем «что за зал» — это про ОДИН конкретный зал («что за зал 5?»),
# а не про перечень; иначе вопрос об одном зале выдал бы дамп всех залов.
#
# Подстроки («какие зал») ломались от любого слова-вставки: «А какие ВООБЩЕ ЕСТЬ
# залы» не матчилось (C25). Поэтому regex, но со СПИСКОМ допустимых вставок, а не
# с `.*`: иначе «какие ЭКСПОНАТЫ в зале» тоже сработало бы, а это вопрос про
# содержимое зала, а не про перечень залов.
_HALL_FILLER = r"(?:\s+(?:вообще|всего|ещё|еще|есть|тут|там|здесь|сейчас|бывают|имеются|у\s+вас|в\s+музее))*"
# Только множественное число («залы»/«залов»): «зал 5» и «в зале» — это вопрос про
# ОДИН зал, перечень выдавать нельзя. «залах» тоже не берём: «в каких залах есть
# яйца» — вопрос про содержимое, а не про список залов.
_HALLS_PLURAL = r"зал(?:ы|ов)\b"
_HALL_LIST_ALTERNATIVES = (
    # «какие (вообще есть) залы», «каких залов»
    r"\bкак(?:ие|их)" + _HALL_FILLER + r"\s+" + _HALLS_PLURAL,
    # «сколько (всего) залов»
    r"\bсколько" + _HALL_FILLER + r"\s+" + _HALLS_PLURAL,
    # «список / перечень / перечисли / назови залы»
    r"\b(?:список|перечень|перечисли|перечислите|назови|назовите)\s+" + _HALLS_PLURAL,
    # «покажи залы», «все залы»
    r"\b(?:покажи|покажите|все|всех|всё)\s+" + _HALLS_PLURAL,
    # «залы музея»
    r"\b" + _HALLS_PLURAL + r"\s+музея\b",
)
_HALL_LIST_RE = re.compile("|".join(_HALL_LIST_ALTERNATIVES), re.IGNORECASE)

# Номер экспоната: реплика по сути состоит только из номера («12», «№ 12»,
# «номер 12», «экспонат 12», «12а»). Разрешаем буквенный суффикс (путеводитель: «12а»).
# Префикс «экспонат…» — только буквы + обязательный пробел, чтобы «экспонат12»
# (без пробела) НЕ разбирался как №2 (жадный \w* съедал бы цифры).
_NUMBER_ONLY_RE = re.compile(
    r"^(?:экспонат[а-яё]*\s+)?(?:№\s*|номер\s*)?(?P<num>\d+[а-яёa-z]?)\s*[.?!]?\s*$",
    re.IGNORECASE,
)


def is_navigational(message: str) -> bool:
    low = message.lower()
    if any(p in low for p in _PAST_MARKERS):
        return False
    return any(p in low for p in _NAV_PATTERNS)


def is_hall_listing(message: str) -> bool:
    """Реплика просит перечень залов («а какие вообще есть залы»)? (C25)

    Устойчиво к словам-вставкам между вопросительным словом и «залы», но не
    срабатывает на вопросы о содержимом зала («какие экспонаты в зале 4»).
    """
    return _HALL_LIST_RE.search(message) is not None


# Маркеры отказа в ответе гида (§4 ТЗ 03.08.2026). Нужны, чтобы отличить
# содержательный ответ от вежливого «не могу»: у отказа нет собственного кода
# возврата — LLM отдаёт его тем же успешным ответом. Признак ставится сразу при
# генерации, потому что постфактум по тексту в БД это уже не восстановить.
_REFUSAL_MARKERS = (
    "не могу предоставить",
    "не могу ответить",
    "не могу помочь",
    "не могу сказать",
    "не располагаю",
    "нет информации",
    "нет данных",
    "не нашёл", "не нашел",
    "не найдено",
    "не знаю",
    "затрудняюсь",
    "к сожалению, у меня нет",
    "в предоставленных материалах",
    "в предоставленной справке",
    "уточните, что именно",
    "уточните, пожалуйста, что",
    # ── Вторая пара со скриншота п. II-3 (баг-репорт 31.08.2026) ────────────
    # Музей проиллюстрировал «предлагаются вопросы, ответы на которые гид не
    # знает» ДВУМЯ парами. Первая («К сожалению, я не знаю, как работает
    # механизм…») ловилась маркером «не знаю». Вторая — «Почему яйцо стало
    # единственным, заказанным герцогиней Мальборо?» → «К сожалению, точных
    # сведений… нет» — не ловилась НИ ОДНИМ маркером: в ней нет ни «не знаю»,
    # ни «не могу», ни «нет данных». Следствие было прямое и молчаливое:
    # `answered` оставался True, строка не попадала ни в отчёт
    # /admin/analytics/unanswered, ни в `crud.exhibit_refused_questions`, и тот
    # же вопрос предлагался снова — то есть ровно тот сбой, на который музей
    # пожаловался, этим релизом не закрывался бы.
    #
    # Хуже: новый промпт диалога (`llm._CHAT_SYSTEM`) прямо запрещает модели
    # «в предоставленных материалах нет информации» и просит сказать о незнании
    # «одной фразой» — то есть уводит её ИМЕННО в эту, неохваченную лексику.
    # Без этих строк детектор после релиза срабатывал бы РЕЖЕ, чем до него.
    #
    # Маркеры широкие намеренно и живут ТОЛЬКО здесь: отделение отказа целиком
    # от честной оговорки посреди содержательного ответа — работа
    # `is_hard_refusal`, и только она решает, прятать ли вопрос у всех.
    "точных сведений",
    "точной информации",
    "сведений об этом нет",
    "не сохранилось",
    "неизвестн",
    "ничего не сказано",
    # Обе формы «не сказано» перечислены поимённо, а не одной подстрокой «не
    # сказано»: голое «не сказано» цепляло бы и содержательное «о мастере не
    # сказано, но яйцо создано в 1894 году», а такой ответ — оговорка, а не отказ.
    "об этом не сказано",
    "нет подробностей",
)

# Постпозитивное «нет» — тот же отказ, только другим порядком слов, и подстрокой
# он не ловится: между существительным и отрицанием стоит что угодно («данных ОБ
# ЭТОМ нет», «сведений о мастере, К СОЖАЛЕНИЮ, нет»), а перечислять такие
# сочетания поимённо — значит проглядеть следующее. Проверено вызовом
# `is_hard_refusal`: «К сожалению, данных об этом нет, уточните, пожалуйста,
# вопрос.» не находила НИ ОДНОГО маркера, то есть отказ не запоминался и вопрос
# предлагался снова — ровно жалоба п. II-3.
#
# Ширина здесь того же сорта, что и у списка выше, и по той же причине безопасна:
# «Данных о заказчике нет, но яйцо изготовлено в 1902 году» маркер найдёт, а
# прятать вопрос всё равно не станет — это решает `is_hard_refusal` по
# предикациям.
#
# Ширина окна между существительным и «нет» — 120 знаков, и это не запас «на
# всякий случай», а измеренная величина. Между ними стоит НЕ вводное слово, а
# придаточное, которое повторяет вопрос посетителя целиком: гид отвечает
# «Данных о том, ПОЧЕМУ ЯЙЦО СТАЛО ЕДИНСТВЕННЫМ ЗАКАЗОМ ГЕРЦОГИНИ МАЛЬБОРО,
# нет.» Длина этого придаточного — это длина вопроса, а вопросы гид предлагает
# сам (`guide_questions`), и они регулярно длиннее 60 знаков.
#
# Прежнее окно в 60 знаков не ловило НИ ОДНУ из пяти формулировок ниже — то есть
# обе пары со скриншота п. II-3 в их естественной развёрнутой форме (проверено
# вызовами: ни `is_refusal`, ни `is_hard_refusal` не срабатывали, отказ не
# запоминался, вопрос предлагался снова). Замеренные расстояния:
#   61 — «Информации о работе механизма со стрелкой-змейкой у меня, к сожалению, нет.»
#   63 — «Сведений о том, как функционирует механизм со стрелкой-змейкой, у меня нет.»
#   63 — «Упоминаний о том, почему герцогиня Мальборо больше ничего не заказывала, нет.»
#   67 — «Данных о том, почему яйцо стало единственным заказом герцогини Мальборо, нет.»
#   74 — «Подробностей о том, почему герцогиня Мальборо заказала только одно яйцо, к сожалению, нет.»
# 120 — это самая длинная замеренная (74) плюс запас примерно в полтора раза:
# следующая формулировка того же сорта будет длиннее, а поштучно догонять их
# каждым баг-репортом дороже, чем один раз взять окно с полем.
#
# Ограничителем ширины остаётся `[^.!?]`: окно не переползает границу
# предложения, поэтому «Данных нет.» + «Яйцо создано в 1902 году.» окном не
# сшиваются. Цена ошибки в эту сторону мала и по той же причине, что и у списка
# маркеров выше: широкий признак лишь отправит ответ в отчёт, а прятать вопрос
# у всех решает `is_hard_refusal` по предикациям. Ложных срабатываний на наборе
# содержательных ответов с оговоркой (`tests/test_guide_intel.py`) нет.
#
# Пять формулировок вынесены в тест константой `REFUSALS_WITH_A_LONG_SUBORDINATE`
# именно затем, чтобы окно нельзя было молча ужать обратно.
_REFUSAL_WINDOW = 120
_REFUSAL_PATTERNS: Tuple[re.Pattern, ...] = (
    re.compile(
        r"\b(?:сведени\w*|данн(?:ых|ые)|информаци\w*|подробност\w*|упоминани\w*)\b"
        r"[^.!?]{0,%d}?\bнет\b" % _REFUSAL_WINDOW
    ),
)


def _has_refusal_marker(text: str) -> bool:
    low = (text or "").lower().replace("ё", "е")
    if any(marker.replace("ё", "е") in low for marker in _REFUSAL_MARKERS):
        return True
    return any(pattern.search(low) for pattern in _REFUSAL_PATTERNS)


def is_refusal(answer: str) -> bool:
    """Похож ли ответ гида на отказ («не могу предоставить полный список»).

    Эвристика по фразам-маркерам ГДЕ УГОДНО в ответе: полноценно отличить отказ
    от ответа можно только по смыслу, но для отчёта «вопросы без ответа» этой
    ширины достаточно и она полезна — отчёт показывает, где не хватает описаний,
    и лишняя строка в нём стоит дёшево (её увидит сотрудник музея и отбросит).

    ВНИМАНИЕ: этой ширины хватает ТОЛЬКО для отчёта. Всё, что прячет вопрос от
    посетителя, обязано спрашивать `is_hard_refusal` — см. её докстринг.
    """
    return _has_refusal_marker(answer)


# ── Из чего состоит «содержательное продолжение» отказа ──────────────────────
# Прежняя редакция мерила хвост ЗНАКАМИ: «есть ли после первой фразы хотя бы 80
# символов». На живых формулировках это ошибалось в ту же сторону, ради которой
# строгий предикат и заводился, — проверено вызовами `is_hard_refusal`, все
# четыре давали True, хотя это содержательные ответы:
#   «Точной даты я не знаю. Яйцо датируют 1902 годом.»
#   «Имя миниатюриста мне неизвестно, нет данных. Портреты выполнены акварелью
#    на кости.»
#   «Не могу сказать, кто был первым владельцем. Яйцо поступило в музей в 2004 году.»
#   «К сожалению, я не знаю его точной цены. Заказ был оплачен из личных средств
#    императора.»
# Это ровно та форма, которую ТРЕБУЕТ промпт диалога («скажи об этом одной фразой
# и расскажи то, что знаешь точно»): факт короткий, а мерили длину. Поэтому хвост
# меряется СМЫСЛОМ — есть ли среди фраз после отказа хоть одна содержательная.

# Обороты, которыми модель ЗАКАНЧИВАЕТ отказ, ничего при этом не сообщив:
# предложение сменить тему и просьба переспросить. Список узкий намеренно —
# «могу рассказать» само по себе сюда не входит, иначе «Могу рассказать, что яйцо
# создал Перхин» посчиталось бы пустой вежливостью и увело бы нормальный вопрос
# из подсказок у всех посетителей.
_POLITE_TAIL_RE = re.compile(
    r"мог(?:у|ла|ли)\b[^.!?]{0,30}?(?:рассказать|показать|предложить|поискать)"
    r"[^.!?]{0,40}?(?:друг|еще|остальн|ином|иное)"
    r"|\bхотите\b"
    r"|\b(?:спросите|переспросите|задайте|попробуйте|обратитесь|уточните)\b"
    r"|чем\s+еще\s+(?:могу|помочь)"
    r"|\b(?:извините|извиняюсь|прошу\s+прощения)\b"
)
_FACT_DIGIT_RE = re.compile(r"\d")

# ── Чем факт присоединяется к оговорке ───────────────────────────────────────
# Прежняя редакция знала ровно две границы: конец предложения и противительный
# союз (`,\s*(?:но|однако|зато)`). Всё остальное оставляло факт ВНУТРИ «первой
# фразы», а значит — внутри отказа. Проверено вызовами `is_hard_refusal`, все
# восемь давали True, хотя каждый сообщает факт:
#   «Точной даты я не знаю; яйцо датируют 1902 годом.»
#   «Точной даты я не знаю — яйцо датируют 1902 годом.»
#   «Точных сведений о заказчике нет: яйцо изготовлено в 1902 году…»
#   «Имя миниатюриста неизвестно, а портреты выполнены акварелью на кости.»
#   «Точной даты я не знаю, яйцо датируют 1902 годом.»
#   «Яйцо датируют 1902 годом, точной даты изготовления я не знаю.»
#   «Яйцо изготовлено в мастерской Перхина, но точных сведений о заказчике нет.»
#   «Браслет создал Эрик Коллин; об истории его поступления в музей ничего не сказано.»
# Последние три — про ПОРЯДОК: факт стоял первым, но маркер попадал в ту же
# первую фразу, и ответ целиком считался отказом. Цена ошибки — `llm_refusal` на
# ОТВЕЧЕННЫЙ вопрос: он прячется из подсказок у всех посетителей экспоната на
# `GUIDE_REFUSAL_MEMORY_DAYS` дней, молча и без следа в логах. Промпт диалога при
# этом сам просит отвечать одной фразой, так что форма частая.
#
# Поэтому ответ режется не на предложения, а на ПРЕДИКАЦИИ: «;», «:», тире и
# запятая — все они одинаково могут присоединять факт, и знак препинания не
# должен решать судьбу вопроса.

# После запятой новую предикацию открывает НЕ всякое слово. Придаточное
# («не знаю, КАК работает механизм…») — это переформулировка вопроса, а не факт:
# оно принадлежит той же фразе отказа, и резать по такой запятой нельзя, иначе
# отказ со скриншота п. II-3 распался бы на «не знаю» + «мнимый факт».
#
# «хотя» в этот список НЕ входит, хотя соблазн есть: «не знаю, хотя вопрос
# интересный» — действительно вежливость, а не факт. Но уступительный оборот в
# русском вводит и факт тоже, и именно такой формы промпт диалога сам добивается
# («скажи о незнании одной фразой и расскажи то, что знаешь точно»):
# «Данных о механизме нет, ХОТЯ фигурка петушка поднимается из крышки каждый
# час» — содержательный ответ. Цена двух ошибок несимметрична: лишний отказ
# прячет нормальный вопрос из подсказок у ВСЕХ посетителей экспоната на
# GUIDE_REFUSAL_MEMORY_DAYS дней и молча, а пропущенная вежливость всего лишь не
# попадает в память подсказок — в отчёт «вопросы без ответа» она всё равно
# придёт по широкому `is_refusal`. Поэтому промахиваемся в дешёвую сторону.
_SUBORDINATE = (
    r"(?:как\w*|что(?:бы)?|кто|кого|кому|кем|где|куда|откуда|когда|почему|зачем|отчего"
    r"|чем|чь\w+|котор\w+|сколько|ли|если|поскольку|потому|пока|прежде|будто|словно)"
)
# Вводные слова тоже не открывают предикацию. Без этого «Уточните, ПОЖАЛУЙСТА,
# что именно вас интересует» распадалось на «Уточните» + «пожалуйста, что…», и
# маркер «уточните, пожалуйста, что» переставал находиться целиком.
_PARENTHETIC = r"(?:пожалуйста|к\s+сожалению|увы|простите|извините|признаться|честно\s+говоря)"
# Пробел после запятой заглядывается ВНУТРИ lookahead, а не съедается до него:
# при `,\s*(?!…)` движок отступает на ноль пробелов, проверяет запрет против
# самого пробела — и режет всё подряд.
_CLAUSE_SPLIT_RE = re.compile(
    r"\s*[;:]\s*"
    r"|\s+[—–-]\s+"
    r"|,(?!\s*(?:" + _SUBORDINATE + r"|" + _PARENTHETIC + r")\b)\s*",
    re.IGNORECASE,
)
# Вводное слово, оторванное запятой от своей же фразы («К сожалению, у меня нет
# сведений»), возвращается на место: иначе распадаются маркеры, которые сами
# содержат запятую («к сожалению, у меня нет»).
_PARENTHETIC_ONLY_RE = re.compile(_PARENTHETIC + r"\Z", re.IGNORECASE)

# ── Обрывки, которые предикацией не являются ─────────────────────────────────
# Запятая, ЗАКРЫВАЮЩАЯ придаточное, для регулярки неотличима от запятой,
# открывающей новую мысль, — а в русском отказе после неё регулярно остаётся
# голое «нет». Проверено вызовами `is_hard_refusal`, все три давали False, хотя
# это отказы целиком:
#   «К сожалению, точных сведений о том, почему яйцо стало единственным заказом
#    герцогини Мальборо, нет.» — вторая пара со скриншота п. II-3 в её
#    естественной полной форме, то есть прямая приёмка задачи;
#   «Точных сведений о мастере, к сожалению, нет.»
#   «Информации об этом, к сожалению, у меня нет.»
# Хвост «нет» шёл отдельной предикацией, маркера в нём нет — и он засчитывался
# за факт: отказ не запоминался, вопрос предлагался снова.
#
# Признак обрывка — не длина, а отсутствие ЗНАМЕНАТЕЛЬНОГО слова: «нет», «у меня
# нет», «их нет» сами по себе не сообщают ничего, сообщает та предикация, к
# которой они относятся. Мерить «короче двух слов», как предлагалось, нельзя:
# «Точной даты не знаю. Мастер — Перхин.» распалось бы на два однословных
# обрывка, и НОРМАЛЬНЫЙ ответ уехал бы в память отказов — ошибка в самую дорогую
# сторону (см. докстринг `_is_substantive`).
#
# Притяжательные местоимения («в МОИХ материалах», «в НАШЕЙ справке») стоят
# здесь же, рядом с остальными местоимениями: без них предикация «в моих
# материалах, нет» оставалась знаменательной и засчитывалась за факт — см.
# `_SOURCE_OF_IGNORANCE_WORDS` ниже.
#
# ВНИМАНИЕ: набор режется `.split()`, поэтому комментариев ВНУТРИ строки быть не
# может — решётка и слова пояснения попали бы в набор служебных слов.
_FUNCTION_WORDS = frozenset(
    """
    нет не ни да же ли бы б и а но то
    я мы ты вы он она оно они
    меня мне мной нас нам вас вам его ему им ее ей их ими них нем нею
    мой моя мое мои моего моей моих моем моим моими моему мою
    наш наша наше наши нашего нашей наших нашем нашим нашими нашему нашу
    это этот эта эти этого этой этом этим тем том
    там тут здесь уже еще увы
    у в во на о об обо при для из от до по с со за над под про без через к ко
    """.split()
)
_WORD_RE = re.compile(r"[а-яa-z0-9]+")

# ── Слова-носители «источника незнания» ──────────────────────────────────────
# Отдельный от служебных класс, и назван он отдельно намеренно: невидимым его
# оставлять нельзя, а к служебным словам он не относится — это полноценные
# существительные. Общее у них другое: в отказе они называют НЕ факт, а место,
# где факта не нашлось. Хвост «…, в моих материалах, нет.» знаменательное слово
# несёт, поэтому засчитывался за факт, и отказ переставал быть отказом целиком
# (проверено вызовами `is_hard_refusal`, все пять давали False):
#   «К сожалению, точных сведений о заказчике, в моих материалах, нет.»
#   «Точных сведений о мастере, в моих источниках, нет.»
#   «Данных об этом, в моём распоряжении, нет.»
#   «Сведений о механизме, в имеющемся описании, нет.»
#   «Сведений о том, почему яйцо стало единственным заказом, в моих материалах, нет.»
#
# Почему всё-таки правим, а не описываем ограничение: промпт диалога
# (`llm._CHAT_SYSTEM`) прямо запрещает модели оборот «в предоставленных
# материалах нет информации» и просит сказать о незнании одной фразой — то есть
# уводит её ровно в эту лексику, и класс будет встречаться часто, а не разово.
#
# Почему это не разворачивает асимметрию цены ошибки (см. `_is_substantive`):
# слова перечислены ТОЧНЫМИ формами предложного падежа, а не основами, и
# `_carries_no_content` требует, чтобы из них состояла ВСЯ предикация. Карточка
# предмета со списком материалов говорит «материалы: золото, эмаль» — форма
# «материалы» в наборе отсутствует, да и «золото» знаменательно, так что
# содержательная фраза мимо не проедет. Проверено на наборе содержательных
# ответов с оговоркой: ложных срабатываний нет.
#
# Вместе с существительными перечислены причастия, которыми модель их определяет
# («в ИМЕЮЩЕМСЯ описании», «в ДОСТУПНЫХ мне материалах»): без них предикация
# опять окажется «знаменательной». Притяжательные местоимения («в МОИХ
# материалах») к этому классу не относятся — они дописаны к служебным словам
# выше, рядом с остальными местоимениями.
_SOURCE_OF_IGNORANCE_WORDS = frozenset(
    """
    материалах источниках знаниях распоряжении описании справке
    имеющемся имеющихся имеющейся доступном доступных
    """.split()
)

# Вводное слово закрывается запятой с ОБЕИХ сторон, и вторая запятая точно так же
# отрывает от фразы её конец: «уточните, пожалуйста, вопрос» → «уточните,
# пожалуйста» + «вопрос». Приклеиваем обратно, но ТОЛЬКО если впереди стоит сама
# вежливая просьба (`_POLITE_TAIL_RE`): содержания у неё нет по определению, а
# факт при ней всё равно опознаётся числом. Общего правила «клеить всё после
# закрывающей запятой» здесь быть не может — оно съело бы факт в «Точной даты я
# не знаю, к сожалению, яйцо датируют 1902 годом».
_POLITE_REQUEST_TAIL_RE = re.compile(r",\s*" + _PARENTHETIC + r"\s*\Z", re.IGNORECASE)


def _carries_no_content(phrase: str) -> bool:
    """Обрывок ли это — ни одного знаменательного слова («нет», «у меня нет»).

    Слова-носители «источника незнания» знаменательны грамматически, но факта не
    сообщают: «в моих материалах» — это место, где факта не нашлось, а не факт
    (см. `_SOURCE_OF_IGNORANCE_WORDS`).
    """
    words = _WORD_RE.findall((phrase or "").lower().replace("ё", "е"))
    return all(
        word in _FUNCTION_WORDS or word in _SOURCE_OF_IGNORANCE_WORDS
        for word in words
    )


def _continues_previous(previous: str, piece: str) -> bool:
    """Продолжение ли это предыдущей предикации, а не новая.

    Три случая, и все три — про запятую, которая ничего не открывает:
      • оторванное вводное слово («К сожалению» + «у меня нет сведений»);
      • обрывок без знаменательных слов («…герцогини Мальборо» + «нет»);
      • конец вежливой просьбы («уточните, пожалуйста» + «вопрос»).
    """
    low = previous.lower().replace("ё", "е")
    if _PARENTHETIC_ONLY_RE.fullmatch(low):
        return True
    if _carries_no_content(piece):
        return True
    return bool(_POLITE_REQUEST_TAIL_RE.search(low) and _POLITE_TAIL_RE.search(low))


def _clauses(text: str) -> List[str]:
    """Разложить ответ на предикации: предложения, а внутри них — части фразы."""
    # Разбиение на предложения берём у guide_style, а не заводим второе: там оно
    # уже умеет не рвать инициалы («Фирма К. Фаберже, мастер М. Перхин»), и два
    # почти одинаковых разбивателя рядом неизбежно разъедутся. Импорт локальный,
    # чтобы модуль разбора намерения не тянул на себя модуль стиля при загрузке.
    from .guide_style import split_sentences

    parts: List[str] = []
    for sentence in split_sentences(text):
        for piece in _CLAUSE_SPLIT_RE.split(sentence):
            piece = (piece or "").strip(" \t\r\n—–-")
            if not piece:
                continue
            if parts and _continues_previous(parts[-1], piece):
                parts[-1] = parts[-1] + ", " + piece
            else:
                parts.append(piece)
    return parts


def _is_substantive(phrase: str) -> bool:
    """Несёт ли фраза что-то по существу — или это продолжение того же отказа.

    Порядок проверок выбран по цене ошибки, а она здесь несимметрична: лишнее
    «содержательно» всего лишь не спрячет вопрос (он останется в подсказках, а
    в отчёт ответ всё равно попадёт по широкому `is_refusal`), а лишнее
    «пусто» — прячет НОРМАЛЬНЫЙ вопрос у всех посетителей экспоната на
    `GUIDE_REFUSAL_MEMORY_DAYS` дней, молча и без следа в логах.

      1. Обрывок без знаменательных слов содержанием не бывает: голое «нет»,
         оторванное запятой от своей же фразы, — это конец отказа, а не факт
         при нём (см. `_carries_no_content`). Обычно такой обрывок уже приклеен
         обратно в `_clauses`; проверка нужна для случая, когда клеить не к
         чему, — ответ, начинающийся с «Нет.».
      2. Фраза с маркером отказа содержательной не считается никогда:
         «Не знаю. Нет данных об этом в моих материалах.» — отказ целиком.
      3. Вежливый оборот — тоже не содержание, НО только если в нём нет числа:
         «Хотите, расскажу, что яйцо создано в 1894 году?» сообщает факт, и
         терять его из-за слова «хотите» нельзя. Число как признак факта — тот
         же приём, что в `guide_style.is_filler_sentence`.
    """
    text = (phrase or "").strip(" \t\r\n—–-")
    if not text:
        return False
    if _carries_no_content(text):
        return False
    if _has_refusal_marker(text):
        return False
    if _POLITE_TAIL_RE.search(text.lower().replace("ё", "е")):
        return bool(_FACT_DIGIT_RE.search(text))
    return True


def is_hard_refusal(answer: str) -> bool:
    """Отказ ли это ЦЕЛИКОМ — так, что вопрос можно прятать из подсказок у всех.

    Зачем нужен отдельный, строгий предикат
        `is_refusal` кормит два разных потребителя, и цена ошибки у них разная.
        Отчёт `/admin/analytics/unanswered` от лишней строки не страдает. А
        глобальная память отказов (решение Д8 по релизу 31.08.2026:
        `crud.exhibit_refused_questions` → `guide_style.clean_questions`) от
        лишней строки прячет НОРМАЛЬНЫЙ вопрос у ВСЕХ посетителей этого
        экспоната на `GUIDE_REFUSAL_MEMORY_DAYS` дней — молча, без следа в логах.

        Ширины `is_refusal` для этого категорически мало: маркер ищется где
        угодно в ответе, а промпт диалога (`llm._CHAT_SYSTEM`) сам просит модель
        писать «Если конкретного факта не знаешь — скажи об этом одной фразой и
        расскажи то, что знаешь точно». То есть на широком признаке мы наказывали
        бы модель ровно за то поведение, которого от неё добиваемся: развёрнутый
        ответ с одной оговоркой «точной даты не знаю» после двух повторов увёл бы
        хороший вопрос из подсказок.

    Что считается отказом целиком
        В ответе есть маркер отказа И НИ ОДНА его предикация не проходит
        `_is_substantive`. Предикация — это часть ответа, отделённая концом
        предложения, «;», «:», тире или запятой (кроме запятой перед придаточным
        и вводным словом, см. `_CLAUSE_SPLIT_RE`). Обрывок, оставшийся от
        запятой, которая придаточное ЗАКРЫВАЕТ, отдельной предикацией не
        считается и приклеивается обратно — см. `_continues_previous`.

        Ни знак, которым присоединён факт, ни его место в ответе роли не играют —
        и то и другое раньше решало судьбу вопроса. Прежняя редакция требовала
        маркер в ПЕРВОЙ фразе, а факт искала только после границы предложения или
        противительного союза, поэтому «Точной даты я не знаю; яйцо датируют 1902
        годом.» и «Яйцо датируют 1902 годом, точной даты я не знаю.» считались
        отказом целиком. Требование «маркер стоит первым» отпало само: если хоть
        одна предикация содержательна — это уже не отказ, где бы она ни стояла.

        Хвост меряется смыслом, а не длиной, — см. комментарий выше: порог в
        знаках резал короткие фактические концовки («Яйцо датируют 1902 годом.»),
        то есть ровно ту форму ответа, которой промпт диалога от модели и
        добивается.

    Приёмка (дословно из замечаний по релизу):
        • «К сожалению, я не знаю, как работает механизм со стрелкой-змейкой в
          яйце герцогини Мальборо.» (скриншот п. II-3) — True;
        • «К сожалению, точных сведений об этом нет.» (вторая пара п. II-3) — True;
        • она же в естественной полной форме, с постпозитивным «нет» за
          закрывающей запятой: «К сожалению, точных сведений о том, почему яйцо
          стало единственным заказом герцогини Мальборо, нет.» — True;
        • содержательный ответ с оговоркой — False, каким бы знаком факт ни был
          присоединён и в каком бы порядке ни стоял.
    """
    text = (answer or "").strip()
    if not text or not _has_refusal_marker(text):
        return False
    return not any(_is_substantive(part) for part in _clauses(text))


def parse_exhibit_number(message: str) -> Optional[str]:
    """Если реплика — это по сути только номер экспоната, вернуть его; иначе None.

    Возвращает и для голого года («1885») — это неоднозначно, поэтому вызывающий
    код (guide.chat) при отсутствии совпадений по номеру должен провалиться в
    обычный диалог, а не выдавать «не нашёл» (B9).
    """
    match = _NUMBER_ONLY_RE.match(message.strip())
    return match.group("num") if match else None
