"""Разбор намерения реплики посетителя для ИИ-гида (B7/B9/B10).

Чистые функции без обращения к БД — легко тестируются автономно. Роутер
`/guide/chat` использует их, чтобы решить: это навигационный вопрос («как найти» —
нужна `location`), запрос списка залов («какие залы» — `referenced_halls`) или
поиск по номеру экспоната («12», «№ 12»).
"""
from __future__ import annotations

import re
from typing import Optional

# Навигация: «как найти», «в каком зале», «где находится», «как пройти»…
# Осознанно не берём голое «где» — слишком широко (напр. «где сделано»).
_NAV_PATTERNS = (
    "как найти", "где найти", "где нахо", "в каком зале", "в какой витрине",
    "как пройти", "как добраться", "где посмотреть", "где увидеть", "где распол",
    "где выставл", "где стоит", "где лежит", "покажи на карте", "как дойти",
    "в каком зал",
)

# Маркеры прошедшего времени: вопрос про историю/провенанс («где выставлялось
# РАНЬШЕ»), а не про текущее местоположение. При них навигацию не включаем —
# иначе к историческому вопросу пришпилится текущий зал/витрина (B7).
_PAST_MARKERS = ("раньше", "ранее", "прежде", "когда-то", "в прошлом")

# Список залов: «какие залы», «список залов», «сколько залов», «перечисли залы»…
# НЕ включаем «что за зал» — это про ОДИН конкретный зал («что за зал 5?»),
# а не про перечень; иначе вопрос об одном зале выдал бы дамп всех залов.
#
# Подстроки («какие зал») ломались от любого слова-вставки: «А какие ВООБЩЕ ЕСТЬ
# залы» не матчилось (C25). Поэтому regex, но со СПИСКОМ допустимых вставок, а не
# с `.*`: иначе «какие ЭКСПОНАТЫ в зале» тоже сработало бы, а это вопрос про
# содержимое зала, а не про перечень залов.
_HALL_FILLER = r"(?:\s+(?:вообще|всего|ещё|еще|есть|тут|там|здесь|сейчас|бывают|имеются|у\s+вас|в\s+музее))*"
# Только множественное число («залы»/«залов»): «зал 5» и «в зале» — это вопрос про
# ОДИН зал, перечень выдавать нельзя. «залах» тоже не берём: «в каких залах есть
# яйца» — вопрос про содержимое, а не про список залов.
_HALLS_PLURAL = r"зал(?:ы|ов)\b"
_HALL_LIST_ALTERNATIVES = (
    # «какие (вообще есть) залы», «каких залов»
    r"\bкак(?:ие|их)" + _HALL_FILLER + r"\s+" + _HALLS_PLURAL,
    # «сколько (всего) залов»
    r"\bсколько" + _HALL_FILLER + r"\s+" + _HALLS_PLURAL,
    # «список / перечень / перечисли / назови залы»
    r"\b(?:список|перечень|перечисли|перечислите|назови|назовите)\s+" + _HALLS_PLURAL,
    # «покажи залы», «все залы»
    r"\b(?:покажи|покажите|все|всех|всё)\s+" + _HALLS_PLURAL,
    # «залы музея»
    r"\b" + _HALLS_PLURAL + r"\s+музея\b",
)
_HALL_LIST_RE = re.compile("|".join(_HALL_LIST_ALTERNATIVES), re.IGNORECASE)

# Номер экспоната: реплика по сути состоит только из номера («12», «№ 12»,
# «номер 12», «экспонат 12», «12а»). Разрешаем буквенный суффикс (путеводитель: «12а»).
# Префикс «экспонат…» — только буквы + обязательный пробел, чтобы «экспонат12»
# (без пробела) НЕ разбирался как №2 (жадный \w* съедал бы цифры).
_NUMBER_ONLY_RE = re.compile(
    r"^(?:экспонат[а-яё]*\s+)?(?:№\s*|номер\s*)?(?P<num>\d+[а-яёa-z]?)\s*[.?!]?\s*$",
    re.IGNORECASE,
)


def is_navigational(message: str) -> bool:
    low = message.lower()
    if any(p in low for p in _PAST_MARKERS):
        return False
    return any(p in low for p in _NAV_PATTERNS)


def is_hall_listing(message: str) -> bool:
    """Реплика просит перечень залов («а какие вообще есть залы»)? (C25)

    Устойчиво к словам-вставкам между вопросительным словом и «залы», но не
    срабатывает на вопросы о содержимом зала («какие экспонаты в зале 4»).
    """
    return _HALL_LIST_RE.search(message) is not None


def parse_exhibit_number(message: str) -> Optional[str]:
    """Если реплика — это по сути только номер экспоната, вернуть его; иначе None.

    Возвращает и для голого года («1885») — это неоднозначно, поэтому вызывающий
    код (guide.chat) при отсутствии совпадений по номеру должен провалиться в
    обычный диалог, а не выдавать «не нашёл» (B9).
    """
    match = _NUMBER_ONLY_RE.match(message.strip())
    return match.group("num") if match else None
