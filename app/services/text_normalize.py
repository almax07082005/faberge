def shorten_to_sentence(text: Optional[str], limit: int, *, min_ratio: float = 0.5) -> str:
    """Обрезать текст до ``limit`` знаков ПО ГРАНИЦЕ ПРЕДЛОЖЕНИЯ, а не по символу.

    Потребителей два, и цена плохого разреза у них разная — поэтому функция одна,
    а порог вынесен в параметр:

      • промпт диалога (``llm._yandexgpt_chat``, ``GUIDE_GROUNDING_MAX_CHARS``) —
        оборванное полуслово модель додумывает и выдаёт за факт, но и слишком
        короткая справка ей бесполезна: ``min_ratio=0.5``, лучше «…», чем полфразы
        контекста;
      • превью описания зала в каталоге — приоритет обратный: обрыв посетитель
        видит глазами, а недобор длины ему не мешает, под превью есть кнопка
        «Подробнее о зале».

    ``min_ratio`` — доля лимита, ближе которой к началу граница фразы уже не
    считается подходящей: если последняя точка попала раньше, режем по слову и
    ставим «…». ``limit <= 0`` или текст короче лимита — текст возвращается
    целиком (обрезка выключена).
    """
    text = (text or "").strip()
    if limit <= 0 or len(text) <= limit:
        return text
    head = text[:limit]
    cut = max(head.rfind(". "), head.rfind("! "), head.rfind("? "), head.rfind("; "))
    if cut >= int(limit * min_ratio):
        return head[: cut + 1].rstrip()
    space = head.rfind(" ")
    return (head[:space] if space > 0 else head).rstrip(" ,;:—-") + "…"
