# Типографика каталога (баг-репорт 06.08.2026, п.9)
# ═════════════════════════════════════════════════════════════════════════════
# Полную вычитку текстов делает музей — мы ловим только СИСТЕМНЫЕ дефекты, те,
# что машина определяет без интерпретации смысла. По выдаче прода 06.08.2026
# (1252 экспоната, поле name): 30 названий с прямыми кавычками при «ёлочках» в
# остальных, 3 названия с разорванным дефисом («пресс- папье»), плюс один
# невидимый LTR-mark внутри «Морозные узоры» (id=81).
#
# Сознательно НЕ трогаем: содержательные опечатки, регистр, тире вместо дефиса
# в перечислениях, неразрывные пробелы — там нужен человек, а не regexp.

CHANGE_QUOTES = "quotes"        # "…" → «…» (внутренние — „…“)
CHANGE_HYPHEN = "hyphen"        # «пресс- папье» → «пресс-папье»
CHANGE_SPACES = "spaces"        # двойные пробелы, хвосты и края
CHANGE_INVISIBLE = "invisible"  # zero-width / bidi-марки внутри строки

# Невидимые символы, попадающие в текст при копировании из PDF и Word: zero-width
# (U+200B..U+200D), метки направления письма (U+200E/200F, U+202A..U+202E),
# word-joiner и BOM. На экране их не видно, но поиск и сортировка по названию
# ломаются: в названии id=81 «Морозные узоры» перед «М» стоит U+200E, и по
# «Морозные» оно не находится. Смысла в подписи такие символы не несут — режем.
_INVISIBLE_RE = re.compile("[\u200b-\u200f\u202a-\u202e\u2060\ufeff]")

# Разорванный дефис ВНУТРИ слова. Ключевое условие — СЛЕВА от дефиса буква без
# пробела: именно это отличает «пресс- папье» от тире в перечислении («поднос,
# чернильница — предметы») и от конструкции «что-то - и дальше», где знак с обеих
# сторон окружён пробелами. Две ветки:
#   • строчная справа — «пресс- папье» (id=358, id=359);
#   • заглавная справа — «Санкт- Петербурга» (id=901): здесь слева обязательно
#     СТРОЧНАЯ буква, а справа заглавная + строчная, то есть настоящее слово, а не
#     инициал; так составное имя собственное чинится, а «Слово- Предложение» в
#     описании не склеивается наугад.
# Перевод строки не съедаем ([ \t], а не \s): перенос — это структура текста.
_HYPHEN_SPLIT_RE = re.compile(
    r"(?<=[A-Za-zА-Яа-яЁё])-[ \t]+(?=[a-zа-яё])"
    r"|(?<=[a-zа-яё])-[ \t]+(?=[A-ZА-ЯЁ][a-zа-яё])"
)

_MULTISPACE_RE = re.compile(r"[ \t]{2,}")
_TRAILING_LINE_SPACE_RE = re.compile(r"[ \t]+(?=\n)")

# Контекст, по которому прямая кавычка опознаётся как открывающая/закрывающая.
# Парность важнее «чётности»: правило «первая открывающая, вторая закрывающая»
# ломается на вложенных кавычках — в каталоге такое есть, id=423
# «Складень трёхстворчатый "Богоматерь Казанская (в возглавии "Спас
# Нерукотворный"), …"», где вторая кавычка — ОТКРЫВАЮЩАЯ вложенную.
# Это НАБОРЫ символов (проверка через ``in``), а не регулярки: тире перечислены
# поштучно — дефис и U+2010..U+2015 (в т. ч. en dash и em dash).
_DASHES = "-‐‑‒–—―"
_BEFORE_OPENING = "([{<«„/" + _DASHES         # что может стоять слева от открывающей
_AFTER_CLOSING = ".,;:!?)]}>»“…/" + _DASHES  # что может стоять справа от закрывающей


@dataclass(frozen=True)
class TypographyResult:
    """Итог чистки одной строки.

    ``changes`` — какие правила сработали (CHANGE_*), чтобы скрипт свёл сводку
    «кавычки: N, дефис: N, пробелы: N» без повторного сравнения строк.
    ``needs_review`` — кавычки не сходятся (непарная или закрывающая без
    открывающей). Такую строку мы НЕ ТРОГАЕМ вовсе и отдаём наружу как есть:
    молча превратить непарную кавычку в «ёлочку» — значит получить мусор,
    который потом никто не найдёт. Пусть её посмотрит музей.
    """

    text: str
    changes: Tuple[str, ...] = ()
    needs_review: bool = False


def _is_opening_quote(prev: str, nxt: str, depth: int) -> bool:
    """Открывающая ли это прямая кавычка (по соседям, а не по порядковому номеру)."""
    prev_is_space = prev == "" or prev.isspace()
    nxt_is_space = nxt == "" or nxt.isspace()
    if (prev_is_space or prev in _BEFORE_OPENING) and not nxt_is_space:
        return True                     # « "Слово» — слева пусто/скобка, справа текст
    if (nxt_is_space or nxt in _AFTER_CLOSING) and not prev_is_space:
        return False                    # «Слово", » — слева текст, справа пробел/знак
    return depth == 0                   # соседи не помогли — решаем по глубине


def _convert_straight_quotes(text: str) -> Optional[str]:
    """Прямые кавычки → «ёлочки» (вложенные → „лапки“).

    Возвращает ``None``, если кавычки не сходятся, — сигнал вызывающему коду
    оставить строку человеку. Глубину считаем с учётом УЖЕ стоящих «ёлочек» и
    „лапок“, поэтому смешанный случай «Ковш "Гордая"» даёт правильное
    «Ковш „Гордая“», а не вторые «ёлочки» внутри первых.
    """
    depth = 0
    out: List[str] = []
    for i, ch in enumerate(text):
        if ch in "«„":
            depth += 1
        elif ch in "»“":
            depth = max(depth - 1, 0)
        elif ch == '"':
            prev = text[i - 1] if i else ""
            nxt = text[i + 1] if i + 1 < len(text) else ""
            if _is_opening_quote(prev, nxt, depth):
                out.append("«" if depth == 0 else "„")
                depth += 1
            else:
                if depth == 0:
                    return None         # закрывающая без открывающей — перекос
                depth -= 1
                out.append("»" if depth == 0 else "“")
            continue
        out.append(ch)
    return None if depth else "".join(out)


def analyze_typography(text: Optional[str]) -> TypographyResult:
    """Чистка типографики строки каталога + отчёт о том, что именно поправлено.

    Чистая функция: ни БД, ни сети, ни LLM — её же гоняем в тестах на реальных
    строках прода. Правки применяются в порядке «сначала символы, потом пробелы»,
    чтобы удаление невидимого символа не оставило после себя двойной пробел.
    """
    if not text:
        return TypographyResult(text=text)  # type: ignore[arg-type]  — None/"" отдаём как пришло

    changes: List[str] = []
    result = text

    without_invisible = _INVISIBLE_RE.sub("", result)
    if without_invisible != result:
        changes.append(CHANGE_INVISIBLE)
        result = without_invisible

    if '"' in result:
        converted = _convert_straight_quotes(result)
        if converted is None:
            # Непарная кавычка. Не чиним ничего вообще: строка целиком уходит в
            # раздел «требует глаз» отчёта, чтобы правку сделал человек, а не мы
            # наугад (заказчик: «вдруг где-то кавычки осмысленные»).
            return TypographyResult(text=text, needs_review=True)
        if converted != result:
            changes.append(CHANGE_QUOTES)
            result = converted

    hyphen_fixed = _HYPHEN_SPLIT_RE.sub("-", result)
    if hyphen_fixed != result:
        changes.append(CHANGE_HYPHEN)
        result = hyphen_fixed

    spaced = _TRAILING_LINE_SPACE_RE.sub("", _MULTISPACE_RE.sub(" ", result)).strip()
    if spaced != result:
        changes.append(CHANGE_SPACES)
        result = spaced

    return TypographyResult(text=result, changes=tuple(changes))


def fix_typography(text: Optional[str]) -> Optional[str]:
    """Короткая форма ``analyze_typography(text).text`` — когда нужен только текст.

    Идемпотентна: результат повторной чистки совпадает с первой (``f(f(x)) == f(x)``),
    поэтому скрипт можно гонять по каталогу сколько угодно раз — второй прогон
    находит ноль замен.
    """
    return analyze_typography(text).text


