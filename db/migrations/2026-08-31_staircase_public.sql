BEGIN;

-- п. I-1, шаг 1 — зал перестаёт быть служебным ---------------------------------
-- Ищем по паре «номер + название», а не по id: id зала в разных окружениях
-- разный (тот же довод, что в db/migrations/2026-08-06_bugreport_iter2.sql).
-- Предикат `is_service` — ради идемпотентности: повторный прогон обновит 0 строк
-- и не дёрнет впустую триггер trg_halls_updated (db/schema.sql), который сам
-- проставляет updated_at, — поэтому updated_at здесь и не перечислен в SET.
UPDATE halls
   SET is_service = false
 WHERE is_service
   AND hall_number = 1
   AND name ILIKE '%парадная лестница%';

-- п. I-1, шаг 2 — порядок, и только если он действительно неверен --------------
-- Порядок залов в выдаче — ORDER BY sort_order, hall_number NULLS LAST
-- (app/crud.py::_HALL_ORDER). На проде у лестницы sort_order = 1, у остальных
-- залов 2…12 и 99, так что этот UPDATE найдёт 0 строк — и это нормально.
--
-- Безусловный `SET sort_order = 1` был бы ОПАСЕН: на окружении, где порядок
-- залам ещё не бэкфилнули (sort_order = 0 по умолчанию, бэкфилл — db/schema.sql),
-- лестница с единицей уехала бы в КОНЕЦ списка вместо начала, то есть правка
-- «поставить первым залом» дала бы ровно обратный результат. Поэтому правим
-- условно и не константой, а «на единицу меньше минимума среди остальных».
UPDATE halls h
   SET sort_order = (SELECT min(sort_order) - 1 FROM halls WHERE id <> h.id)
 WHERE h.hall_number = 1
   AND h.name ILIKE '%парадная лестница%'
   AND h.sort_order > (SELECT min(sort_order) FROM halls WHERE id <> h.id);

COMMIT;

-- ── Проверка (psql -f печатает результат прямо в консоль) ────────────────────
-- 1) Первые три зала публичной выдачи в том же порядке, что отдаёт GET /halls.
--    Ожидаем первой строкой №1 «Парадная лестница» с is_service = f. Пустая
--    выборка означает, что зала в базе нет (урезанный демо-сид).
SELECT id, hall_number, name, is_service, sort_order
  FROM halls
 WHERE NOT is_service
 ORDER BY sort_order, hall_number NULLS LAST
 LIMIT 3;

-- 2) Сколько пронумерованных залов увидит посетитель. Ровно это число назовёт
--    гид во фразе «В музее N залов» (app/routers/guide.py::_describe_halls).
--    Ожидаем 12 — столько же, сколько в путеводителе музея; до отмены решения
--    было 11, и это был побочный эффект, который музей просил снять.
SELECT count(*) AS numbered_public_halls
  FROM halls
 WHERE NOT is_service
   AND hall_number IS NOT NULL;

