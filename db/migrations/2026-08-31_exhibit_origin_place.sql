-- =============================================================================
-- Миграция: место создания экспоната отдельной колонкой
--           (баг-репорт заказчика 31.08.2026, п. I-2 «Унифицировать карточку предмета»)
--
-- Проблема
--   На скриншоте карточки яйца «Ландыши» музей красным дописал, что над названием
--   должна идти «Дата создания И МЕСТО». Даты в карточке есть (year_created), места
--   нет вовсе: каталожная строка путеводителя начинается именно с него —
--       «Санкт-Петербург, 1899–1903. Фирма К. Фаберже, мастер М. Перхин. …»
--   — и парсер app/services/catalog_line.py место давно выделяет
--   (ParsedLine.origin_place), но складывать его было некуда. Дословная цитата из
--   докстринга парсера: «origin_place и provenance в колонки не пишутся (таких
--   колонок нет)» — они уходили только в отчёт бэкфилла, глазами заказчику.
--
-- Что делает
--   Добавляет одну nullable-колонку exhibits.origin_place. Данные НЕ трогает:
--   заполнение идёт отдельно и обратимо — scripts/backfill_exhibit_origin_place.py
--   (сухой прогон по умолчанию, --apply, файл отката, --rollback). Разделение
--   «схема отдельно, данные отдельно» здесь принципиально: прод-БД нам недоступна
--   (админ-токена прода нет), и всё, что меняет данные, обязано быть скриптом с
--   сухим прогоном, а не строчкой UPDATE внутри миграции.
--
-- Чего НЕ делает
--   • Не заполняет колонку из short_description. Разбор каталожной строки — это
--     эвристика на 1252 карточках; в SQL её не выразить, а главное — бэкфилл не
--     имеет права перезаписывать непустое поле, и это правило живёт в скрипте.
--   • Не трогает search_vector. Вектор покрывает прозу (name, master_name,
--     short_description, raw_history); место создания — того же класса, что
--     material и year_created, которые в него сознательно не входят. Технически
--     это ещё и невозможно «между делом»: на живой БД колонка search_vector уже
--     существует, и ADD COLUMN IF NOT EXISTS её выражение МОЛЧА НЕ ИЗМЕНИТ —
--     понадобился бы ALTER COLUMN … SET EXPRESSION (PostgreSQL 17, полная
--     перезапись таблицы) либо DROP+ADD с пересозданием idx_exhibits_search и
--     синхронной правкой всех трёх копий выражения (db/schema.sql в CREATE TABLE,
--     db/schema.sql в ALTER и app/models.py::_EXHIBIT_TSV).
--   • Не заводит колонок firm/master. «Фирма и мастер» из того же пункта музея
--     отдаются РАЗБОРОМ поля master_name при сериализации ответа
--     (catalog_line.split_maker) — форму записи фирм музей оставил за собой, и
--     фиксировать наше предположение колонкой нельзя. См.
--     docs/task-2026-08-31-exhibit-card.md.
--
-- Применение к живой БД
--   psql "$DATABASE_URL" -f db/migrations/2026-08-31_exhibit_origin_place.sql
--   (scripts/init_db.py применяет db/schema.sql целиком и уже содержит этот ALTER —
--    на чистой базе миграция не нужна.)
--
-- Идемпотентна и обратима — см. секцию «Откат» ниже.
-- =============================================================================

BEGIN;

-- TEXT, а не VARCHAR(n): место в указателе бывает многосоставным («Московская
-- губерния, Дмитровский уезд, село Горбуново»), а усечение означало бы потерю
-- данных путеводителя. Пустое место — NULL, не пустая строка: «места не знаем» и
-- «место пустое» для карточки одно и то же, и двух способов записать это быть не должно.
ALTER TABLE exhibits ADD COLUMN IF NOT EXISTS origin_place TEXT;

COMMENT ON COLUMN exhibits.origin_place IS
    'Место создания дословно как в путеводителе: «Санкт-Петербург», «Швейцария, Женева». '
    'Показывается рядом с датировкой (year_created). Заполняется бэкфиллом из каталожной '
    'строки short_description; пусто — NULL.';

COMMIT;

-- ── Проверка (psql -f печатает результат прямо в консоль) ────────────────────

-- Ожидаем одну строку: origin_place | text | YES.
SELECT column_name, data_type, is_nullable
  FROM information_schema.columns
 WHERE table_name = 'exhibits' AND column_name = 'origin_place';

-- Ожидаем 0 ПРИ ПЕРВОМ применении: миграция только заводит колонку, заполняет её бэкфилл.
-- После scripts/backfill_exhibit_origin_place.py --apply тот же запрос покажет, сколько мест
-- уже проставлено, — и это нормально, а не признак поломки. Миграция идемпотентна
-- (ADD COLUMN IF NOT EXISTS), данные она не трогает ни при первом прогоне, ни при повторном.
SELECT count(*) FILTER (WHERE origin_place IS NOT NULL) AS with_place FROM exhibits;

-- Сколько работы предстоит бэкфиллу: карточки с непустой каталожной строкой и
-- пустым местом. Точное число даст сухой прогон скрипта — он, в отличие от SQL,
-- умеет отличить каталожную строку от связной музейной прозы.
SELECT count(*) AS candidates
  FROM exhibits
 WHERE coalesce(short_description, '') <> ''
   AND coalesce(origin_place, '') = '';

