--  Миграция: баг-репорт заказчика «Итерация багов №2» (06.08.2026), п.2 —
--  «Выставочный зал (№9) помечен is_temporary»
--
--  Проблема:
--    Зал никуда не пропадал: в проде это id=8, hall_number=9, 5 витрин + группа
--    «не в витринах», 85 экспонатов — ровно как в путеводителе. Но на зале стоит
--    is_temporary=true, поэтому на стартовом экране он уходит в отдельную ветку
--    «Временная выставка» (GET /halls?is_temporary=true), а в основной экспозиции
--    (is_temporary=false) его нет — заказчик решил, что зал вообще не завели.
--
--  Откуда взялся флаг (чтобы не вернулся):
--    1) db/migrations/2026-07-14_add_hall_is_temporary.sql — разметка «под текущую
--       экспозицию» одной строкой по названию:
--         UPDATE halls SET is_temporary = true WHERE name ILIKE '%выставочный зал%';
--       Название совпало, но «Выставочный зал» Шуваловского дворца — постоянный
--       зал экспозиции (№9 в путеводителе, камнерезные изделия и живопись XIX в.),
--       а не пространство сменных выставок. Ту миграцию не переприменять.
--    2) db/seed_fabergemuseum.sql — тот же флаг ставился повторно (WHERE id = 8);
--       в этой итерации из сида убран, иначе баг возвращался бы после переналивки.
--    Больше нигде is_temporary=true не проставляется: в app/ флаг только читается
--    (фильтры каталога) и пишется явным PATCH /admin/halls/{id} из админки.
--
--  Что делает:
--    снимает is_temporary у зала №9 и печатает залы, у которых флаг остался
--    (требование «заодно проверить остальные залы»). На 06.08.2026 в проде
--    is_temporary=true стоял ТОЛЬКО у зала №9, поэтому ожидаемый результат
--    второй проверки — пустая выборка.
--    sort_order трогать не нужно: у зала уже 9, и в выдаче он встаёт между
--    Голубой гостиной (№8) и Готическим залом (№10), как и просит заказчик.
--
--  Применение к живой БД (Yandex Managed PostgreSQL):
--    psql "$DATABASE_URL" -f db/migrations/2026-08-06_bugreport_iter2.sql
--  ВНИМАНИЕ: в отличие от предыдущих миграций, `python scripts/init_db.py`
--  этого НЕ сделает — скрипт применяет только db/schema.sql (DDL) и db/seed.sql,
--  а здесь правка данных живого каталога. Эквивалент из админки, если доступа к
--  psql нет: PATCH /admin/halls/8 {"is_temporary": false}.
--
--  Идемпотентна (повторный прогон обновит 0 строк), INSERT/ON CONFLICT не
--  содержит, на урезанной dev-базе без этого зала просто ничего не находит.
--  Обратима — см. секцию «Откат» ниже.
-- ============================================================================

BEGIN;

-- п.2 — зал №9 возвращается в основную экспозицию ------------------------------
-- Ищем по паре «номер + название», а не по id: id зала в разных окружениях
-- разный (в проде id=8 при hall_number=9), UPDATE по id молча промахнулся бы.
--   • hall_number = 9 — номер по путеводителю; так зал пронумерован в проде
--     после того, как «Белая и Голубая гостиные» из сида разъехались на два
--     зала и все последующие номера сдвинулись на +1;
--   • hall_number = 8 — тот же зал в базах, залитых db/seed_fabergemuseum.sql
--     до этого разделения (там «Выставочный зал» ещё №8);
--   • name ILIKE — не украшение, а страховка от того же сдвига номеров: без неё
--     в «дореформенной» базе под №9 попал бы Готический зал, а под №8 — Голубая
--     гостиная. Демо-база db/seed.sql под условие не подходит осознанно: там
--     «Выставочный зал» — синтетический №5 и is_temporary=true у него по делу,
--     как демонстрация самой фичи временных выставок.
-- Предикат `is_temporary` — ради идемпотентности: повторный прогон обновит 0 строк
-- и не дёрнет впустую триггер trg_halls_updated (db/schema.sql), который сам
-- проставляет updated_at, — поэтому updated_at здесь и не перечислен в SET.
-- От случайного снятия флага у по-настоящему временных залов страхует не он,
-- а связка hall_number + name: под неё не попадает ни один другой зал прода
-- (hall_number=8 там — «Голубая гостиная», по имени не проходит).
UPDATE halls
   SET is_temporary = false
 WHERE is_temporary
   AND hall_number IN (8, 9)
   AND name ILIKE '%выставочный зал%';

COMMIT;

-- ── Проверка (psql -f печатает результат прямо в консоль) ────────────────────
-- 1) Сам зал №9: ожидаем is_temporary = f. Пустая выборка означает, что зала в
--    базе нет (урезанный dev-сид) либо он назван иначе — тогда снимите флаг
--    вручную по результату проверки №2.
SELECT id, hall_number, name, is_temporary, is_service, sort_order
  FROM halls
 WHERE hall_number IN (8, 9) AND name ILIKE '%выставочный зал%'
 ORDER BY hall_number;

-- 2) Какие залы остались помеченными как временная выставка (п.2: «флаг должен
--    стоять только у действительно временных выставок»). Ожидаемо 0 строк:
--    сменных выставок в экспозиции сейчас нет. Если строки есть — сверьтесь с
--    музеем, что это живая временная выставка, а не след импорта.
SELECT id, hall_number, name, is_temporary
  FROM halls
 WHERE is_temporary
 ORDER BY sort_order, hall_number;

