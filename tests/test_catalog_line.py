def _mismatches(case: Case):
    """Расхождения разбора с ожиданием — списком, чтобы упавший тест показал все сразу."""
    got = parse_catalog_line(case.text)
    errors = []
    if got.status != case.status:
        errors.append(f"status: ждали {case.status}, получили {got.status}")
    for title, expected, actual in (
        ("origin_place", case.place, got.origin_place),
        ("year_created", case.dating, got.year_created),
        ("year_lower", case.year, got.year_lower),
        ("master_name", case.master, got.master_name),
        ("material", case.material, got.material),
        ("techniques", case.techniques, got.techniques),
        ("provenance", case.provenance, got.provenance),
    ):
        if expected != actual:
            errors.append(f"{title}: ждали {expected!r}, получили {actual!r}")
    for label in case.parts:
        if not any(label in note for note in got.notes):
            errors.append(f"метка части {label!r} не упомянута в notes: {got.notes}")
    return errors


def test_all_prod_cases():
    """53 реальные строки прода: разбор совпадает с ручной сверкой по путеводителю."""
    failures = []
    for case in CASES:
        errors = _mismatches(case)
        if errors:
            failures.append(f"id={case.exhibit_id} [{case.form}] {case.note}\n    "
                            + "\n    ".join(errors))
    assert not failures, "\n" + "\n".join(failures)


def test_parse_rate_not_below_95_percent():
    """Доля разобранных среди строк, которые РАЗБИРАТЬСЯ ОБЯЗАНЫ.

    Целевое покрытие спеки — не хуже 96,9 % (1015 карточек из 1048 на проде). В выборке
    из 53 случаев шесть заведомо неразбираемых (проза и битые строки), они в знаменатель
    не идут: их пропуск — правильное поведение, а не потеря.
    """
    parsable = [case for case in CASES if case.status != STATUS_SKIPPED]
    parsed = [case for case in parsable if parse_catalog_line(case.text).status != STATUS_SKIPPED]
    rate = len(parsed) / len(parsable)
    assert rate >= 0.95, f"разобрано {len(parsed)}/{len(parsable)} = {rate:.1%}"
    # И обратная сторона: то, что разбирать нельзя, не разобрано ни в одном случае.
    for case in CASES:
        if case.status == STATUS_SKIPPED:
            assert parse_catalog_line(case.text).status == STATUS_SKIPPED, case.exhibit_id


