def test_dating_precision_ladder():
    """Восемь видов точности датировки: year_lower — всегда НИЖНЯЯ граница."""
    samples = (
        ("1911", 1911, "exact"),
        ("1899–1903", 1899, "range"),
        ("1880-е", 1880, "decade"),
        ("1880–1890-е", 1880, "range_decade"),
        ("1880-е — первая половина 1890-х", 1880, "range_decade"),
        ("около 1825", 1825, "circa"),
        ("ок. 1700", 1700, "circa"),
        ("не позднее 1899", 1899, "before"),
        ("до 1895", 1895, "before"),
        ("после 1903", 1903, "after"),
        ("1831 (?)", 1831, "exact"),
        # Век в число не превращаем: «конец XIX века» стал бы 1801 и сломал сортировку.
        ("конец XIX века", None, "century"),
        ("конец XIX — начало XX века", None, "century"),
        ("рубеж XIX–XX веков", None, "century"),
        ("первая треть XIX века", None, "century"),
        ("начало XX века (?)", None, "century"),
        ("вторая половина XVI века, антикварная реставрация XIX века", None, "century"),
    )
    for dating, year, precision in samples:
        line = parse_catalog_line(f"Москва, {dating}. Фирма К. Фаберже. Серебро; чеканка")
        assert (line.year_created, line.year_lower, line.precision) == (dating, year, precision), dating


